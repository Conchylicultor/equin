// Globally-shared brand. `Symbol.for` returns the same Symbol across module
// reloads (HMR), worker pools, and even separate copies of @plugins/jobs that
// might exist if a worktree links it through different paths. That makes
// `isSuspendSignal()` robust where `instanceof SuspendSignal` would silently
// fail when the class identity differs between the throw and the catch.
const SUSPEND_BRAND: unique symbol = Symbol.for(
  "@plugins/jobs:SuspendSignal",
) as never;

// Suspend sentinel thrown by `ctx.waitFor` and `ctx.sleep`. Caught by the
// worker's dispatch — graphile sees the handler as succeeded, the job row is
// released, and the workflow resumes later via a new enqueue from
// `jobs.resume` (event-triggered) or a scheduled `jobs.resume` (timeout).
//
// The class itself is intentionally NOT exported from the plugin barrel —
// users should not need `instanceof SuspendSignal`. If a user MUST catch
// errors around a `ctx.*` call (e.g. wrapping in their own retry), they
// should re-throw via the exported `isSuspendSignal()` helper. Swallowing
// a SuspendSignal hangs the workflow; the brand-based detector is the
// supported escape hatch.
export class SuspendSignal extends Error {
  // Brand shows up on the instance for `isSuspendSignal()`. Read-only and
  // non-enumerable so it doesn't leak into JSON / log serialisation.
  readonly [SUSPEND_BRAND] = true;
  constructor(public readonly reason: "wait" | "sleep") {
    super(
      `[jobs] workflow suspended (${reason}) — must not be caught by user code`,
    );
    this.name = "SuspendSignal";
  }
}

// Brand check that survives module-identity differences. Use this in any
// intentional catch around `ctx.step` / `ctx.waitFor` / `ctx.sleep`:
//
//     try { await ctx.waitFor(...); }
//     catch (err) { if (isSuspendSignal(err)) throw err; ... }
export function isSuspendSignal(err: unknown): boolean {
  return (
    typeof err === "object" &&
    err !== null &&
    (err as Record<symbol, unknown>)[SUSPEND_BRAND] === true
  );
}

// An `EventSource` shape from @plugins/infra/plugins/events/server. We do not import the
// type here because the jobs plugin must not depend on events (events already
// depends on jobs; a reverse edge would close the cycle). Duck-typed via the
// `__kind === "event"` brand and the `def.name` / `filter` fields.
interface EventSourceLike {
  readonly __kind: "event";
  readonly def: { name: string };
  readonly filter: Record<string, unknown>;
}

// Options accepted by `ctx.waitFor`. `match` is reserved for post-v1 — the
// current implementation ignores it and the event filter is whatever `where`
// encodes via the events plugin's typed filter columns.
export interface WaitForOptions<T> {
  where?: Partial<T>;
  match?: (payload: T) => boolean;
  /**
   * Max time to wait before the handler resumes with `null`. Omitting it no
   * longer means "wait forever" — it falls back to {@link
   * DEFAULT_WAIT_TIMEOUT_MS} and any value is clamped to {@link
   * MAX_WAIT_TIMEOUT_MS}. To wait forever, set `unbounded: true` instead.
   */
  timeoutMs?: number;
  /**
   * Deliberate escape hatch for the rare genuinely-unbounded wait: skip the
   * timeout racer entirely so the wait resolves only when its event fires.
   * Greppable by design (`unbounded: true`) so every forever-wait is auditable.
   * Takes precedence over `timeoutMs` if both are somehow set.
   */
  unbounded?: true;
  /** Override the autogenerated wait name (`wait:<eventName>:<seq>`). */
  name?: string;
  /**
   * What this wait is for, read again once its wake-up is armed — required,
   * because an event only reaches a wait whose trigger exists when it fires.
   *
   * A durable wait is "observe, then wait": the caller reads its state, finds
   * the thing not done yet, and calls `waitFor`. Anything that lands between
   * that read and the trigger being armed is an event nobody hears, and the
   * wait runs out its whole timeout on something already over. On 2026-11-20
   * a quarter of spare-worktree launches waited exactly 30 s this way: the
   * spawn read its checkout run open, started the agent (~1.5 s), and the run
   * ended in between (`prepareWorktree`).
   *
   * - `{ recheck }` — read the condition again AFTER the trigger and the
   *   timeout racer are armed. `true` (it happened) resolves the wait at once
   *   — `waitFor` returns `null`, like a timeout: go and look — and cancels
   *   the racer; `false` suspends, and the armed trigger cannot miss it now.
   * - `{ noRecheck: "<why>" }` — there is nothing to re-read (a wait for the
   *   NEXT occurrence of something, which no state records), said in words.
   */
  readonly settled:
    | { readonly recheck: () => Promise<boolean> }
    | { readonly noRecheck: string };
}

// Hook registry for cross-plugin calls. The events plugin installs
// `registerTrigger` at module-load (see `plugins/events/server/internal/
// install-jobs-hooks.ts`). We avoid a static `import` from events to keep
// the plugin graph acyclic (events already imports jobs).
export interface DurableHooks {
  registerTrigger: (spec: {
    event: EventSourceLike;
    // Pinned to the `jobs.resume` input contract (jobs owns both this
    // interface and ResumeInputSchema), so the worker's construction of
    // `with` is compile-checked against the schema the dispatcher parses.
    with: ResumeInput;
    where: Record<string, unknown>;
    oneShot: boolean;
  }) => Promise<void>;
}

const hooks: Partial<DurableHooks> = {};

/**
 * Returns a {@link Registration} token. The actual `Object.assign(hooks, impl)`
 * fires when the framework invokes `.register()` during the plugin register
 * phase. Plugins list the result in their `register` array.
 */
export function UNSAFE_installDurableHooks(impl: DurableHooks): Registration {
  return {
    _kind: "durable-hooks",
    _factory: "UNSAFE_installDurableHooks",
    _doc: {},
    register() {
      Object.assign(hooks, impl);
    },
  };
}

// Internal identity passed to `makeDurableCtx` by the worker. Encapsulates
// the values ctx.step / ctx.waitFor need to key their durable rows and to
// re-enqueue the handler on resume.
export interface DurableCtxInit {
  jobId: string;
  attempt: number;
  workflowRunId: string;
  jobName: string;
  originalInput: unknown;
  /** The event the run was triggered with, handed back on resume. */
  originalEvent: unknown;
  /**
   * Aborted when this dispatch's execution budget expires. One controller per
   * dispatch, owned by `dispatch()` in worker.ts. Surfaced to handlers as
   * `ctx.signal` — the doc that explains what it is for, and what it is NOT,
   * lives on `JobCtx.signal` in registry.ts, which is the one users read.
   */
  signal: AbortSignal;
  /**
   * Enqueue a job for suspension bookkeeping. The worker passes the registry's
   * own enqueue so we don't recurse through the public barrel. Returns void —
   * we only need to know it scheduled.
   */
  scheduleResume: (
    payload: ResumeInput,
    opts: { jobKey: string; runAt?: Date },
  ) => Promise<void>;
}

export interface DurableCtx {
  /**
   * Graphile job id. Stable across retries of a single failed job, distinct
   * per emit. Use as the dedup key in event-triggered handlers: non-oneShot
   * subscribers MUST dedup on `jobId` rather than the trigger row's UUID,
   * which is identical for every emit of the same trigger.
   */
  jobId: string;
  attempt: number;
  workflowRunId: string;
  /**
   * This dispatch's execution-budget signal. Handed straight through from
   * `DurableCtxInit`; the user-facing contract is documented on
   * `JobCtx.signal` in registry.ts.
   */
  readonly signal: AbortSignal;
  step<R>(name: string, fn: () => Promise<R> | R): Promise<R>;
  waitFor<T extends Record<string, unknown>>(
    event: EventSourceLike & { __t?: T },
    opts: WaitForOptions<T>,
  ): Promise<T | null>;
  sleep(ms: number): Promise<void>;
}

export function makeDurableCtx(init: DurableCtxInit): DurableCtx {
  // Per-invocation counters: wait-seq resets every handler entry so the Nth
  // `ctx.waitFor(E)` call on replay reuses the same name it had on the first
  // run. Branching handlers should pass `opts.name` to stay stable.
  const seqByEvent = new Map<string, number>();

  const nextWaitName = (eventName: string, override?: string): string => {
    if (override) return override;
    const n = seqByEvent.get(eventName) ?? 0;
    seqByEvent.set(eventName, n + 1);
    return `wait:${eventName}:${n}`;
  };

  /**
   * A pending wait met again on replay: the run was dispatched while its wait
   * was still pending — two resumes raced, or its worker died after writing
   * the wait and before arming its waker, and the reclaimed retry replays to
   * here. Suspending again is right only while the waker still holds its key
   * (`keysInFlight`); one that is gone will never resolve the wait, and the
   * run would park where nothing reaches it. So the wait ends now, as timed
   * out (only if still pending: a racer that resolved it first wins, and its
   * resume re-dispatches the run). Whether THIS call ended it.
   */
  const endOrphanedWait = async (
    waitName: string,
    wakerKey: string | null,
  ): Promise<boolean> => {
    if (wakerKey === null) return false;
    const held = await JobQueue.get().keysInFlight([wakerKey]);
    if (held.has(wakerKey)) return false;
    const ended = await db
      .update(_jobWaits)
      .set({ status: "timed_out", resolvedAt: new Date() })
      .where(
        and(
          eq(_jobWaits.workflowRunId, init.workflowRunId),
          eq(_jobWaits.waitName, waitName),
          eq(_jobWaits.status, "pending"),
        ),
      )
      .returning({ waitName: _jobWaits.waitName });
    return ended.length > 0;
  };

  return {
    jobId: init.jobId,
    attempt: init.attempt,
    workflowRunId: init.workflowRunId,
    signal: init.signal,

    async step<R>(name: string, fn: () => Promise<R> | R): Promise<R> {
      const existing = await db
        .select()
        .from(_jobSteps)
        .where(
          and(
            eq(_jobSteps.workflowRunId, init.workflowRunId),
            eq(_jobSteps.stepName, name),
          ),
        )
        .limit(1);
      const row = existing[0];
      if (row) {
        if (row.errorMessage) {
          throw new Error(`[jobs.step "${name}"] ${row.errorMessage}`);
        }
        return (row.resultJson?.v ?? undefined) as R;
      }
      let result: R;
      try {
        result = await fn();
      } catch (err) {
        if (isSuspendSignal(err)) throw err;
        const msg = err instanceof Error ? err.message : String(err);
        await db
          .insert(_jobSteps)
          .values({
            workflowRunId: init.workflowRunId,
            stepName: name,
            errorMessage: msg,
          })
          .onConflictDoNothing();
        throw err;
      }
      await db
        .insert(_jobSteps)
        .values({
          workflowRunId: init.workflowRunId,
          stepName: name,
          // Wrap in `{ v }` so the jsonb round-trips `null` / `undefined`
          // without collapsing into the top-level null the column stores for
          // "no recorded result".
          resultJson: { v: result === undefined ? null : (result as unknown) },
        })
        .onConflictDoNothing();
      return result;
    },

    async waitFor<T extends Record<string, unknown>>(
      event: EventSourceLike & { __t?: T },
      opts: WaitForOptions<T>,
    ): Promise<T | null> {
      const eventName = event.def.name;
      const waitName = nextWaitName(eventName, opts.name);

      const existing = await db
        .select()
        .from(_jobWaits)
        .where(
          and(
            eq(_jobWaits.workflowRunId, init.workflowRunId),
            eq(_jobWaits.waitName, waitName),
          ),
        )
        .limit(1);
      const row = existing[0];
      if (row) {
        if (row.status === "resolved") {
          return (row.payloadJson ?? null) as T | null;
        }
        if (row.status === "timed_out") return null;
        // `status === "pending"`: a rare replay-while-still-pending case
        // (e.g. the handler was resumed twice by concurrent forces). The
        // trigger is still armed from the first suspend, so suspend again
        // without re-registering — unless its waker is gone.
        if (await endOrphanedWait(waitName, row.wakerKey)) return null;
        throw new SuspendSignal("wait");
      }

      // First time reaching this wait. Record a pending row (naming the
      // racer that will surely wake it, armed below), register the event
      // trigger, schedule the timeout, then suspend.
      const resolvedTimeoutMs = resolveWaitTimeoutMs(
        opts.timeoutMs,
        opts.unbounded,
      );
      const timeoutKey =
        resolvedTimeoutMs === null
          ? null
          : `jobs.resume.timeout:${init.workflowRunId}:${waitName}`;
      await db
        .insert(_jobWaits)
        .values({
          workflowRunId: init.workflowRunId,
          waitName,
          status: "pending",
          wakerKey: timeoutKey,
        })
        .onConflictDoNothing();

      if (!hooks.registerTrigger) {
        throw new Error(
          "[jobs] ctx.waitFor called but events plugin hooks are not installed. " +
            "Import @plugins/infra/plugins/events/server somewhere (its side-effect wires this up).",
        );
      }

      const mergedFilter: Record<string, unknown> = {
        // eslint-disable-next-line @typescript-eslint/no-unnecessary-condition -- runtime guard; event.filter may be undefined at runtime
        ...(event.filter ?? {}),
        ...(opts.where ?? {}),
      };

      await hooks.registerTrigger({
        event,
        with: {
          [RESUME_KEYS.workflowRunId]: init.workflowRunId,
          [RESUME_KEYS.waitName]: waitName,
          [RESUME_KEYS.jobName]: init.jobName,
          [RESUME_KEYS.input]: init.originalInput,
          [RESUME_KEYS.event]: init.originalEvent,
        },
        where: mergedFilter,
        oneShot: true,
      });

      // Always arm a timeout racer unless the caller explicitly opts out via
      // `unbounded`. An omitted `timeoutMs` resolves to the engine default, so a
      // forgotten timeout can no longer suspend the run forever.
      if (resolvedTimeoutMs !== null && timeoutKey !== null) {
        await init.scheduleResume(
          {
            [RESUME_KEYS.workflowRunId]: init.workflowRunId,
            [RESUME_KEYS.waitName]: waitName,
            [RESUME_KEYS.jobName]: init.jobName,
            [RESUME_KEYS.input]: init.originalInput,
            [RESUME_KEYS.event]: init.originalEvent,
            [RESUME_KEYS.timeout]: true,
          },
          {
            jobKey: timeoutKey,
            runAt: new Date(Date.now() + resolvedTimeoutMs),
          },
        );
      }

      // Both wakers are armed: anything from here on reaches the wait. What
      // happened before them did not — so ask once more (`settled`).
      if ("recheck" in opts.settled && (await opts.settled.recheck())) {
        const moved = await db
          .update(_jobWaits)
          .set({
            status: "resolved",
            payloadJson: null,
            resolvedAt: new Date(),
          })
          .where(
            and(
              eq(_jobWaits.workflowRunId, init.workflowRunId),
              eq(_jobWaits.waitName, waitName),
              eq(_jobWaits.status, "pending"),
            ),
          )
          .returning({ waitName: _jobWaits.waitName });
        if (moved.length > 0) {
          if (timeoutKey !== null) {
            await JobQueue.get().cancelUnstarted({ key: timeoutKey });
          }
          // Recorded as resolved with no payload, so a replay reads `null`
          // here too. The armed one-shot trigger, if its event never comes,
          // stays exactly as a timed-out wait's does; if it comes, its
          // resume finds the wait resolved and does nothing.
          return null;
        }
        // A waker resolved it first — and in the same transaction queued this
        // run's resume. Going on here would run the workflow twice: suspend,
        // and let that resume carry it.
      }

      throw new SuspendSignal("wait");
    },

    async sleep(ms: number): Promise<void> {
      const waitName = nextWaitName("__sleep");
      const existing = await db
        .select()
        .from(_jobWaits)
        .where(
          and(
            eq(_jobWaits.workflowRunId, init.workflowRunId),
            eq(_jobWaits.waitName, waitName),
          ),
        )
        .limit(1);
      const row = existing[0];
      if (row) {
        if (row.status === "resolved" || row.status === "timed_out") return;
        if (await endOrphanedWait(waitName, row.wakerKey)) return;
        throw new SuspendSignal("sleep");
      }

      const sleepKey = `jobs.resume.sleep:${init.workflowRunId}:${waitName}`;
      await db
        .insert(_jobWaits)
        .values({
          workflowRunId: init.workflowRunId,
          waitName,
          status: "pending",
          wakerKey: sleepKey,
        })
        .onConflictDoNothing();

      await init.scheduleResume(
        {
          [RESUME_KEYS.workflowRunId]: init.workflowRunId,
          [RESUME_KEYS.waitName]: waitName,
          [RESUME_KEYS.jobName]: init.jobName,
          [RESUME_KEYS.input]: init.originalInput,
          [RESUME_KEYS.event]: init.originalEvent,
          [RESUME_KEYS.timeout]: true,
        },
        {
          jobKey: sleepKey,
          runAt: new Date(Date.now() + Math.max(0, ms)),
        },
      );

      throw new SuspendSignal("sleep");
    },
  };
}
