import type { z } from "zod";
import type { FieldsRecord, InferFieldsObject } from "@plugins/fields/core";
import type { ConfigMigration } from "./config-migration";

export type JsonValue =
  string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

export interface Disposable {
  dispose(): void;
}

// The values of a config = the inferred object of its FieldsRecord. Kept as a
// LOCAL alias — NOT `export { … } from "@plugins/fields/core"`. A cross-plugin
// re-export is banned by the boundary checker (`cross-plugin-reexport`); this
// local declaration is the legal form. Do NOT "simplify" it into a re-export.
export type ConfigValues<F extends FieldsRecord = FieldsRecord> =
  InferFieldsObject<F>;

// Where a config descriptor came from. `manual` is hand-authored `defineConfig`
// (the default); the rest are auto-generated by a primitive, one descriptor per
// instance: `reorder` (one per reorderable render slot) and `view` (one per
// DataView consumer's `viewsDescriptor`). Named `source` — NOT `origin` — to
// avoid colliding with config_v2's `.origin.jsonc` code/git layer terminology.
export type ConfigSource = "manual" | "reorder" | "view";

// Where the bytes of this descriptor's generated `<name>.origin.jsonc` come
// from. `descriptor` (almost everything) means the origin is a plain
// materialization of `defaults` below. `build` means an `OriginDefaultsProvider`
// computes them during codegen, from something only the build can see — today
// reorder's live contribution catalog, walked out of the primed plugin tree.
//
// It is declared rather than inferred because it is the BASIS a staleness check
// compares an origin's `// @hash` against. A reader that wants to know whether a
// committed origin is current hashes `descriptor.defaults` and compares — correct
// for the `descriptor` arm and permanently wrong for the `build` arm, whose
// committed hash is over the materialized document and so never matches. The
// declaration is what lets such a reader require the arm it can actually answer
// for (`readGitLayerConfig` takes `ConfigDescriptor<F, "descriptor">`), instead of
// a comment asking callers not to.
export type OriginDefaultsFrom = "descriptor" | "build";

export interface ConfigDescriptor<
  F extends FieldsRecord = FieldsRecord,
  O extends OriginDefaultsFrom = OriginDefaultsFrom,
> {
  readonly name: string;
  readonly schema: z.ZodObject<Record<string, z.ZodType>>;
  readonly fields: F;
  readonly defaults: ConfigValues<F>;
  // Whether `defaults` above IS this descriptor's origin document, or only a
  // placeholder the build replaces. Always set by `defineConfig` (defaults to
  // `descriptor`); see {@link OriginDefaultsFrom} for why it is declared.
  readonly originDefaultsFrom: O;
  // Optional scope axis. When set, this descriptor can be forked per scope of
  // the given kind (e.g. "app" → per-app). Omitted = global-only (base scope).
  readonly scope?: "app";
  // Provenance: hand-authored vs auto-generated. Always set by `defineConfig`
  // (defaults to `manual`). Surfaced as a filterable field + row tag in the
  // settings config nav.
  readonly source?: ConfigSource;
  // When set, this descriptor's committed git-layer override
  // (`config/<tree>/<name>.jsonc`) is MANDATORY, not optional: the build seeds a
  // missing one from the origin and re-marks a stale one, in both cases with a
  // `@review` marker the author must delete — that deletion IS the claim that
  // the values are deliberate. Absent = today's behaviour (override optional,
  // nothing seeded).
  //
  // `guidance` is descriptor-supplied prose, written into the seeded file as
  // comment lines. The seeding engine never authors family-specific text, so a
  // new family that owes an authored override costs zero engine edits.
  // Comment lines the build keeps at the top of EVERY committed override of
  // this descriptor (`config/<tree>/<name>.jsonc` and its `@app/<id>/` forks),
  // as a `// @legend` block right under `// @hash`: how to hand-write this
  // descriptor's values. Re-stamped on every build because nothing else keeps
  // it — the runtime writer re-serializes the document without comments, and
  // an author editing the file deletes what they don't need today. The block is
  // build-owned: hand edits inside it are overwritten.
  readonly overrideLegend?: readonly string[];
  // One-time rewrites of this config's SAVED values after the shape its fields
  // store changed, applied by the build to each namespace's user layer once
  // (see `defineConfigMigration`). In declaration order; never remove one that
  // may not have run everywhere yet.
  readonly migrations?: readonly ConfigMigration[];
  readonly requiresAuthoredOverride?: {
    guidance: string[];
    // "Is there anything here to author?" — the descriptor's own answer, asked
    // once, right before a MISSING override would be seeded. Returning false
    // means this default is vacuous: there is no arrangement to make, so a
    // seeded file would be a no-op the human can only rubber-stamp, and asking
    // for that review buries the files where a real decision IS pending.
    // Omitted = always seed (the original behaviour).
    //
    // The argument is the ORIGIN's effective defaults — the exact document
    // seeding would write, i.e. `descriptor.defaults` already run through the
    // build's `OriginDefaultsProvider`. Families that materialize their default
    // at build time (reorder's live contribution catalog) would see nothing in
    // `descriptor.defaults`, so reading anything else here would be wrong.
    //
    // Gates SEEDING ONLY, never registration: the descriptor stays live, so an
    // override that already exists is never pruned, re-seeded or ignored when
    // the answer later flips to false.
    seedWhen?: (defaults: Record<string, unknown>) => boolean;
  };
}
