/**
 * Marker appended to a plugin's `name — description` line when the app's own
 * composition does not bundle it. Excluded plugins STAY in the docs (the code
 * still exists) but are annotated. Deterministic — never names the negative that
 * caused it (several could match, which would make the marker ambiguous and churn
 * the in-sync check):
 *  - named directly by a negative entry pattern: ` (excluded)`
 *  - taken by the removal cascade (a descendant, or an importer that would break
 *    without it): ` (excluded — cascade)`
 */
function exclusionMarker(p: PluginNode, main: MainComposition): string {
  if (main.bundle.has(p.id)) return "";
  return main.negated.has(p.id) ? " (excluded)" : " (excluded — cascade)";
}

const BEGIN =
  "<!-- AUTOGENERATED:BEGIN — do not edit; regenerated by `./equin build` -->";
/**
 * Finds an existing block's BEGIN line by its marker, not its full text: the
 * wording after the marker (the CLI name it cites) may change, and an exact
 * match would then miss every existing block and append a second one.
 */
const BEGIN_LINE = /^<!-- AUTOGENERATED:BEGIN\b.*$/m;
const END = "<!-- AUTOGENERATED:END -->";

function readIfExists(path: string): string | null {
  return existsSync(path) ? readFileSync(path, "utf8") : null;
}

function pluginDescription(p: PluginNode): string | undefined {
  const parts = [
    p.descriptions.web,
    p.descriptions.server,
    p.descriptions.central,
  ].filter((d): d is string => Boolean(d));
  return parts.length > 0 ? joinDescriptions(parts) : p.description;
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * A fact's values are rendered one-per-line as a nested list — a comma-joined
 * blob of 40 importers is unreadable and rewrites the whole line in a diff when
 * a single entry is added. A lone value stays inline (it is already on its own
 * line; nesting it would only add noise).
 *
 * A list too long to print in full (`isSummarized`) prints one count per group
 * instead, still one per line, and links `referenceLink` — the plugin's
 * `REFERENCE.md`, where `renderPluginReferenceMd` lists it in full.
 */
function renderDocFacts(
  facts: DocFact[],
  bodyIndent: string,
  referenceLink: string,
): string[] {
  const subIndent = `${bodyIndent}  `;
  const valueIndent = `${subIndent}  `;
  const lines: string[] = [];
  const folders = new Map<string, DocFact[]>();
  for (const f of facts) {
    let group = folders.get(f.folder);
    if (!group) {
      group = [];
      folders.set(f.folder, group);
    }
    group.push(f);
  }
  for (const [folder, group] of folders) {
    const content: string[] = [];
    for (const fact of group) {
      if (isSummarized(fact)) {
        content.push(
          `${subIndent}- ${fact.key}: ${summaryCount(fact)} — full list in ${referenceLink}`,
        );
        for (const line of summaryLines(fact))
          content.push(`${valueIndent}- ${line}`);
        continue;
      }
      const values = docFactValues(fact);
      if (values.length === 0) continue;
      if (values.length === 1) {
        content.push(`${subIndent}- ${fact.key}: ${values[0]}`);
        continue;
      }
      content.push(`${subIndent}- ${fact.key}:`);
      for (const value of values) content.push(`${valueIndent}- ${value}`);
    }
    if (content.length > 0) {
      lines.push(`${bodyIndent}- ${capitalize(folder)}:`);
      lines.push(...content);
    }
  }
  return lines;
}

/**
 * Every fact the facets document about `p`. Facts whose folder a runtime
 * declares undocumented are dropped here — the one place every generated doc
 * funnels through, so no facet has to know (or repeat) the policy, and this
 * renderer never names a folder.
 */
function collectPluginFacts(
  p: PluginNode,
  facets: Facet[],
  root: string,
): DocFact[] {
  const allFacts: DocFact[] = [];
  for (const facet of facets) {
    const data = getFacet(p, facet.def);
    if (data !== undefined) {
      const facts = facet.renderDoc(data, { root });
      assertNoTestCodeInFacts({ pluginId: p.id, facetId: facet.def.id, facts });
      allFacts.push(...facts);
    }
  }
  return allFacts.filter((f) => !UNDOCUMENTED_RUNTIME_FOLDERS.has(f.folder));
}

function renderPluginFacts(
  p: PluginNode,
  facets: Facet[],
  bodyIndent: string,
  root: string,
  referenceLink: string,
  lines: string[],
): void {
  lines.push(
    ...renderDocFacts(
      collectPluginFacts(p, facets, root),
      bodyIndent,
      referenceLink,
    ),
  );
}

/**
 * The plugin's `REFERENCE.md`: every list its CLAUDE.md summarizes, in full,
 * one value per line — or null when nothing was summarized (no file). Not named
 * `CLAUDE*.md`, so it is never auto-loaded: agents open it when they need a
 * list, instead of paying for it on every read of the plugin.
 */
export function renderPluginReferenceMd(
  p: PluginNode,
  root: string,
  facets: Facet[],
): string | null {
  const summarized = collectPluginFacts(p, facets, root).filter(isSummarized);
  if (summarized.length === 0) return null;
  const lines = [
    `# ${p.name} — full reference lists`,
    "",
    "The lists this plugin's `CLAUDE.md` summarizes, in full. Generated by `./equin build` — do not edit.",
  ];
  for (const fact of summarized) {
    lines.push(
      "",
      `## ${capitalize(fact.folder)} — ${fact.key} (${summaryCount(fact)})`,
      "",
    );
    for (const value of docFactValues(fact)) lines.push(`- ${value}`);
  }
  return lines.join("\n") + "\n";
}

type RenderMode = "detail" | "compact";

function subtreeHasTestHelpers(p: PluginNode): boolean {
  return (
    collectTestHelpers(p).length > 0 || p.children.some(subtreeHasTestHelpers)
  );
}

/** Whether the plugin declares exemptions of its own (an `exempt/index.ts` with entries). */
function hasExemptions(p: PluginNode): boolean {
  return (getFacet(p, exemptionsFacetDef)?.declared.length ?? 0) > 0;
}

function subtreeHasExemptions(p: PluginNode): boolean {
  return hasExemptions(p) || p.children.some(subtreeHasExemptions);
}

function countDescendants(p: PluginNode): number {
  let n = 0;
  for (const c of p.children) n += 1 + countDescendants(c);
  return n;
}

function renderPluginTreeMd(
  p: PluginNode,
  depth: number,
  root: string,
  mode: RenderMode,
  facets: Facet[],
  main: MainComposition,
): string[] {
  const headerIndent = "  ".repeat(depth);
  const bodyIndent = `${headerIndent}  `;
  const lines: string[] = [];
  const desc = pluginDescription(p);
  const shown = desc && mode === "compact" ? capDescription(desc) : desc;
  const descStr = shown ? ` — ${shown}` : "";
  const lbMarker = mode === "compact" && p.loadBearing ? " [load-bearing]" : "";
  // A collapsed entry hides its sub-tree, so it carries the marker when any
  // plugin inside it publishes helpers.
  const thMarker =
    mode === "compact" &&
    (p.collapsed ? subtreeHasTestHelpers(p) : collectTestHelpers(p).length > 0)
      ? " [test helpers]"
      : "";
  // Same rule for `[exempt]`: a plugin that exempts itself from a rule.
  const exemptMarker =
    mode === "compact" &&
    (p.collapsed ? subtreeHasExemptions(p) : hasExemptions(p))
      ? " [exempt]"
      : "";
  const exMarker = exclusionMarker(p, main);

  if (mode === "compact" && p.collapsed && p.children.length > 0) {
    const total = countDescendants(p);
    const subLabel = total === 1 ? "1 sub-plugin" : `${total} sub-plugins`;
    lines.push(
      `${headerIndent}- **\`${p.name}\`**${lbMarker}${thMarker}${exemptMarker} [${subLabel}]${exMarker}${descStr}`,
    );
    return lines;
  }

  lines.push(
    `${headerIndent}- **\`${p.name}\`**${lbMarker}${thMarker}${exemptMarker}${exMarker}${descStr}`,
  );

  const includeBody = mode === "detail";
  if (includeBody) {
    const refPath = relative(join(root, "docs"), pluginReferenceMdPath(p));
    renderPluginFacts(
      p,
      facets,
      bodyIndent,
      root,
      `[\`${relative(root, pluginReferenceMdPath(p))}\`](${refPath})`,
      lines,
    );
    lines.push(...renderTestHelpers(collectTestHelpers(p), bodyIndent));
  }

  if (p.children.length > 0) {
    lines.push(`${bodyIndent}- Plugins:`);
    for (const c of p.children)
      lines.push(...renderPluginTreeMd(c, depth + 2, root, mode, facets, main));
  }

  return lines;
}

export interface GenerateDocsOptions {
  root: string;
}

export async function collectAllPlugins(root: string): Promise<PluginNode[]> {
  const tree = await buildBarrelFreeTree(root);
  return Array.from(tree.byDir.values());
}

function renderTreeBody(
  roots: PluginNode[],
  root: string,
  mode: RenderMode,
  facets: Facet[],
  main: MainComposition,
): string {
  const lines: string[] = [];
  for (let i = 0; i < roots.length; i++) {
    if (i > 0) lines.push("");
    lines.push(...renderPluginTreeMd(roots[i]!, 0, root, mode, facets, main));
  }
  return lines.join("\n") + "\n";
}

const COMPACT_HEADER =
  "# Plugins (compact)\n\n" +
  "Slim, always-loaded index of every plugin. Shows only `name — description`; load-bearing infrastructure plugins are marked `[load-bearing]`; plugins publishing shared test fixtures (`<runtime>/testing/` barrels) are marked `[test helpers]` (a collapsed entry, when any plugin inside it does), listed under *Test helpers* in the details doc; plugins that exempt some of their own files from a lint rule or check (their `exempt/index.ts`) are marked `[exempt]`, the rule and who is exempted listed in the details doc and by `./equin exempt list`; collapsed plugins show `[N sub-plugins]` — open the plugin's own `CLAUDE.md` for its full sub-tree. Read [`plugins-details.md`](./plugins-details.md) for the full reference, or open the per-plugin `CLAUDE.md` when working inside a specific plugin.\n\n";

const DETAILS_HEADER =
  "# Plugins (details)\n\n" +
  "Full reference for every plugin. Read this on demand (e.g. before writing a helper or a test fixture, to check whether one already exists). A plugin's *Test helpers* item lists its `<runtime>/testing/` barrels: shared fixtures that only test code may import. The slim always-loaded index is [`plugins-compact.md`](./plugins-compact.md).\n\n" +
  `A list longer than ${DOC_LIST_MAX} values (importers, uses, contributions) is summarized here and in the plugin's CLAUDE.md as one count per group; the linked \`REFERENCE.md\` beside the plugin lists it in full.\n\n`;

export async function renderCompactDoc({
  root,
}: GenerateDocsOptions): Promise<string> {
  return renderCompactDocFromTree(await buildEnrichedTree(root), root);
}

export async function renderDetailsDoc({
  root,
}: GenerateDocsOptions): Promise<string> {
  return renderDetailsDocFromTree(await buildEnrichedTree(root), root);
}

function renderPluginClaudeAutogen(
  p: PluginNode,
  root: string,
  facets: Facet[],
  main: MainComposition,
): string {
  const lines: string[] = [];
  lines.push("## Plugin reference");
  lines.push("");
  const desc = pluginDescription(p);
  if (desc) lines.push(`- Description: ${desc}`);
  if (p.loadBearing) lines.push("- Load-bearing: yes");
  // Annotate plugins the app's composition leaves out (the code still exists,
  // but it's omitted from the registries/bundle). Directly negated vs taken by
  // the cascade, deterministic — never names the causing negative (see
  // `exclusionMarker`).
  if (!main.bundle.has(p.id)) {
    lines.push(
      main.negated.has(p.id) ? "- Excluded: yes" : "- Excluded: cascade",
    );
  }
  renderPluginFacts(
    p,
    facets,
    "",
    root,
    "[REFERENCE.md](./REFERENCE.md)",
    lines,
  );
  lines.push(...renderTestHelpers(collectTestHelpers(p), ""));
  if (p.children.length > 0) {
    if (p.collapsed) {
      lines.push("- Sub-plugins:");
      for (const c of p.children) {
        lines.push(...renderPluginTreeMd(c, 1, root, "compact", facets, main));
      }
    } else {
      lines.push("- Sub-plugins:");
      for (const c of p.children) {
        const cdesc = pluginDescription(c);
        const cdescStr = cdesc ? ` — ${capDescription(cdesc)}` : "";
        const cExMarker = exclusionMarker(c, main);
        lines.push(`  - **\`${c.name}\`**${cExMarker}${cdescStr}`);
      }
    }
  }
  return lines.join("\n") + "\n";
}

/**
 * Strip any hand-written `## Plugin reference` section from a CLAUDE.md prose
 * prefix (the content before the AUTOGENERATED:BEGIN marker).
 *
 * When the autogenerated system was introduced it *appended* a block (which
 * itself opens with `## Plugin reference`) to files that already had a
 * hand-written section of the same name. The hand-written copy predates the
 * autogen system and drifts silently; the autogenerated block is the
 * authoritative, more-complete source of truth. This helper removes the stale
 * hand-written copy so only the autogenerated one remains.
 *
 * It also strips any dangling `AUTOGENERATED:END` marker left in the prose
 * by a prior manual edit that removed the matching BEGIN (the conflict-agent
 * anomaly).
 */
function stripStalePluginReference(prose: string): string {
  // Remove the last ## Plugin reference section in the prose and everything
  // that follows it (up to the end of the prose prefix). Using lastIndexOf
  // picks only the copy that sits immediately above the autogen block.
  const refMarker = "\n## Plugin reference\n";
  const refIdx = prose.lastIndexOf(refMarker);
  let cleaned = refIdx !== -1 ? prose.slice(0, refIdx) + "\n" : prose;

  // Remove any dangling AUTOGENERATED:END markers left without a matching BEGIN.
  cleaned = cleaned.replace(/<!--\s*AUTOGENERATED:END\s*-->\n?/g, "");

  return cleaned;
}

function renderPluginClaudeMd(
  p: PluginNode,
  existing: string | null,
  root: string,
  facets: Facet[],
  main: MainComposition,
): string {
  const autogen = renderPluginClaudeAutogen(p, root, facets, main);
  const block = `${BEGIN}\n\n${autogen}\n${END}\n`;

  if (existing === null) {
    return `# ${p.name}\n\n${block}`;
  }
  return spliceAutogenBlock(existing, block);
}

/**
 * `existing` with its autogen block replaced by `block` (appended when it has
 * none), the hand-written prose above it kept.
 */
export function spliceAutogenBlock(existing: string, block: string): string {
  const beginIdx = existing.search(BEGIN_LINE);
  if (beginIdx < 0) {
    const sep = existing.endsWith("\n") ? "\n" : "\n\n";
    return `${existing}${sep}${block}`;
  }
  const endIdx = existing.indexOf(END, beginIdx);
  if (endIdx < 0) {
    return `${existing.slice(0, beginIdx)}${block}`;
  }
  const after = existing.slice(endIdx + END.length);
  const trimmedAfter = after.startsWith("\n") ? after.slice(1) : after;
  const prose = stripStalePluginReference(existing.slice(0, beginIdx));
  return `${prose}${block}${trimmedAfter}`;
}

export function pluginCompactDocPath(root: string): string {
  return join(root, "docs", "plugins-compact.md");
}

export function pluginDetailsDocPath(root: string): string {
  return join(root, "docs", "plugins-details.md");
}

export function pluginClaudeMdPath(p: PluginNode): string {
  return join(p.dir, "CLAUDE.md");
}

export function pluginReferenceMdPath(p: PluginNode): string {
  return join(p.dir, "REFERENCE.md");
}

function legacyPluginDocsPath(root: string): string {
  return join(root, "docs", "plugins.md");
}

export async function generatePluginDocs({
  root,
}: GenerateDocsOptions): Promise<void> {
  const tree = await buildEnrichedTree(root);
  const main = mainComposition(tree, root);

  // Markdown is not in the format allowlist, so the funnel hands these bytes
  // back untouched — they route through it anyway so there is exactly one write
  // idiom for generated artifacts, with no per-extension opt-in to forget.
  await writeGenerated({
    file: pluginCompactDocPath(root),
    content: renderCompactDocFromTree(tree, root),
  });
  await writeGenerated({
    file: pluginDetailsDocPath(root),
    content: renderDetailsDocFromTree(tree, root),
  });

  for (const info of tree.byDir.values()) {
    const file = pluginClaudeMdPath(info);
    // The renderer needs the CURRENT file (it rewrites only the AUTOGEN block
    // and preserves the hand-written prose around it), so the read stays here.
    const existing = readIfExists(file);
    await writeGenerated({
      file,
      content: renderPluginClaudeMd(info, existing, root, tree.facets, main),
    });
    // Written only for a plugin whose CLAUDE.md summarizes a list, and removed
    // once none does, so the file's presence tracks the source either way.
    const refFile = pluginReferenceMdPath(info);
    const reference = renderPluginReferenceMd(info, root, tree.facets);
    if (reference !== null) {
      await writeGenerated({ file: refFile, content: reference });
    } else if (existsSync(refFile)) {
      unlinkSync(refFile);
    }
  }

  const legacy = legacyPluginDocsPath(root);
  if (existsSync(legacy)) {
    try {
      unlinkSync(legacy);
      // eslint-disable-next-line promise-safety/no-bare-catch
    } catch {
      // Best-effort
    }
  }
}

function renderCompactDocFromTree(tree: PluginTree, root: string): string {
  const body = renderTreeBody(
    tree.roots,
    root,
    "compact",
    tree.facets,
    mainComposition(tree, root),
  );
  return `${COMPACT_HEADER}${BEGIN}\n\n${body}\n${END}\n`;
}

function renderDetailsDocFromTree(tree: PluginTree, root: string): string {
  const pluginsBody = renderTreeBody(
    tree.roots,
    root,
    "detail",
    tree.facets,
    mainComposition(tree, root),
  );
  // Reverse index over every plugin's routes: the prediction debt, per gap.
  const debt = renderPredictionDebt(
    predictionDebt(
      [...tree.byDir.values()].map((info) => ({
        plugin: info.path,
        data: getFacet(info, routesFacetDef),
      })),
    ),
  );
  const body =
    debt.length === 0 ? pluginsBody : `${pluginsBody}\n${debt.join("\n")}\n`;
  return `${DETAILS_HEADER}${BEGIN}\n\n${body}\n${END}\n`;
}

