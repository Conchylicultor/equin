// A browser host's plugin graph, generated: the registry entries a page's Web
// Worker boots (`server-core`'s `bootBrowserHost`).
//
// A host declares the plugins it serves as plain data, in
// `plugins/<p>/bin/browser-host.plugins.ts` (`export const hostPlugins = [...]`
// — the features it answers, plus the providers of a host without the
// computer). Its graph is the SERVER BARRELS those plugins' server code
// actually loads, measured with `importClosure` — not their `dependsOn`
// closure, which follows every cross-plugin import (a `core/` constant
// included) and so would pull in server barrels the graph never reaches, most
// of them not portable. Each entry's `dependsOn` is the server registry's raw
// edges, kept to the graph. The bundle then reaches exactly these barrels.
//
// Written beside the declaration as `bin/browser-host.generated.ts`, committed,
// and held to this render by `plugins-registry-in-sync`.

import type { RepoFiles } from "@plugins/framework/plugins/tooling/core";
import { importClosure } from "@plugins/framework/plugins/tooling/plugins/import-closure/core";
import {
  scanCollectedDir,
  type RegistryGenContext,
} from "./plugin-registry-gen";
import { writeGenerated } from "./write-generated";

const DECLARATION_RE =
  /^plugins\/((?:[^/]+\/plugins\/)*[^/]+)\/bin\/browser-host\.plugins\.ts$/;

const SERVER_BARREL_RE =
  /^plugins\/((?:[^/]+\/plugins\/)*[^/]+)\/server\/index\.ts$/;

const HEADER = [
  "// DO NOT EDIT — autogenerated by `./singularity build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/browser-host-gen.ts).",
  "//",
  "// This browser host's plugin graph: every server barrel the plugins listed in",
  "// `./browser-host.plugins.ts` load. The `plugins-registry-in-sync` check fails",
  "// on drift.",
].join("\n");

/** One host: the plugin declaring it, and its generated file. */
export interface BrowserHostDecl {
  /** The declaring plugin's path (`apps/plugins/agent-manager/plugins/demo`). */
  pluginPath: string;
  /** Repo-relative `bin/browser-host.plugins.ts`. */
  declaration: string;
  /** Repo-relative `bin/browser-host.generated.ts`. */
  generated: string;
}

/** Every browser host the repo declares. */
export function discoverBrowserHosts(repo: RepoFiles): BrowserHostDecl[] {
  const hosts: BrowserHostDecl[] = [];
  for (const path of repo.all()) {
    const m = DECLARATION_RE.exec(path);
    if (m === null) continue;
    hosts.push({
      pluginPath: m[1]!,
      declaration: path,
      generated: path.replace(/\.plugins\.ts$/, ".generated.ts"),
    });
  }
  return hosts.sort((a, b) => a.pluginPath.localeCompare(b.pluginPath));
}

/**
 * The host's declared plugins, read off the declaration's text: one array
 * literal of plain strings, so the generator and the check read the same file
 * through the run's file set and never evaluate it.
 */
async function declaredPlugins(
  repo: RepoFiles,
  host: BrowserHostDecl,
): Promise<readonly string[]> {
  const text = (await repo.read(host.declaration)) ?? "";
  const list = /export const hostPlugins = \[([^\]]*)\]/.exec(text);
  const plugins = [...(list?.[1] ?? "").matchAll(/"([^"]+)"/g)].map(
    (m) => m[1]!,
  );
  if (plugins.length === 0) {
    throw new Error(
      `${host.declaration} must export \`export const hostPlugins = ["<plugin path>", …]\` — a non-empty array of string literals.`,
    );
  }
  return plugins;
}

/** The generated file of one host, rendered from the current source. */
export async function renderBrowserHost(
  ctx: RegistryGenContext,
  host: BrowserHostDecl,
): Promise<string> {
  const repo = await ctx.repo();
  const plugins = await declaredPlugins(repo, host);
  const graph = new Set<string>();
  for (const p of plugins) {
    const barrel = `plugins/${p}/server/index.ts`;
    if (!repo.has(barrel)) {
      throw new Error(
        `${host.declaration} lists "${p}", which has no server barrel (${barrel}).`,
      );
    }
    // What the bundler loads from this barrel, as the bundle will.
    const closure = await importClosure(ctx.root, barrel, {
      dynamicImports: "cut",
    });
    for (const module of closure.modules) {
      const m = SERVER_BARREL_RE.exec(module);
      if (m !== null) graph.add(m[1]!);
    }
  }

  const { deps } = await scanCollectedDir(ctx, "server");
  const lines = [
    HEADER,
    "",
    'import type { ServerRegistryEntry } from "@plugins/framework/plugins/server-core/core";',
    "",
    "export const hostEntries: ServerRegistryEntry[] = [",
  ];
  for (const pluginPath of [...graph].sort()) {
    const dependsOn = (deps.get(pluginPath) ?? []).filter((d) => graph.has(d));
    lines.push(
      `  { pluginPath: ${JSON.stringify(pluginPath)}, id: ${JSON.stringify(pluginPath.split("/plugins/").join("."))}, loader: () => import(${JSON.stringify(`@plugins/${pluginPath}/server`)}), dependsOn: ${JSON.stringify(dependsOn)} },`,
    );
  }
  lines.push("];", "");
  return lines.join("\n");
}

/** Write every host's generated graph. */
export async function generateBrowserHosts(
  ctx: RegistryGenContext,
): Promise<void> {
  for (const host of discoverBrowserHosts(await ctx.repo())) {
    await writeGenerated({
      file: `${ctx.root}/${host.generated}`,
      content: await renderBrowserHost(ctx, host),
    });
  }
}
