import { describe, expect, test } from "bun:test";
import { loadRepoSnapshot } from "@plugins/framework/plugins/tooling/core";
import { REPO_ROOT } from "@plugins/infra/plugins/paths/plugins/repo-root/core";
import { autogenFixedPoint, spliceAutogenBlock } from "./autogen-block";

const END = "<!-- AUTOGENERATED:END -->";
const block = (body: string) =>
  `<!-- AUTOGENERATED:BEGIN — new wording -->\n\n${body}\n${END}\n`;

describe("spliceAutogenBlock", () => {
  test("replaces a block whose BEGIN line has older wording, never duplicating it", () => {
    const existing = [
      "# p",
      "",
      "Prose.",
      "",
      "<!-- AUTOGENERATED:BEGIN — do not edit; regenerated by `./old-cli build` -->",
      "",
      "- stale",
      END,
      "",
    ].join("\n");
    const out = spliceAutogenBlock(existing, block("- fresh"));
    expect(out).toBe(`# p\n\nProse.\n\n${block("- fresh")}`);
    expect(out.match(/AUTOGENERATED:BEGIN/g)).toHaveLength(1);
  });

  test("appends a block to prose that has none", () => {
    expect(spliceAutogenBlock("# p\n", block("- x"))).toBe(
      `# p\n\n${block("- x")}`,
    );
  });

  test("a marker mentioned mid-line in prose is not a block", () => {
    const existing = "# p\n\nThe `<!-- AUTOGENERATED:BEGIN` marker.\n";
    expect(spliceAutogenBlock(existing, block("- x"))).toBe(
      `${existing}\n${block("- x")}`,
    );
  });
});

describe("autogenFixedPoint", () => {
  const prose = "# p\n\nProse.\n\n";

  test("the block a synced file holds; splicing it changes nothing", () => {
    const file = `${prose}${block("- x")}tail\n`;
    expect(autogenFixedPoint(file)).toBe(block("- x"));
    expect(spliceAutogenBlock(file, block("- x"))).toBe(file);
  });

  test("no block leaves a file unchanged when splicing would rewrite it", () => {
    // No block at all: splicing appends one.
    expect(autogenFixedPoint(prose)).toBeNull();
    // BEGIN with no END: splicing replaces everything from BEGIN on.
    expect(
      autogenFixedPoint(`${prose}<!-- AUTOGENERATED:BEGIN x -->\n- y\n`),
    ).toBeNull();
    // No newline after END: the block always ends with one.
    expect(autogenFixedPoint(`${prose}${block("- x").trimEnd()}`)).toBeNull();
    // A hand-written `## Plugin reference` above the block: splicing strips it.
    expect(
      autogenFixedPoint(`# p\n\n## Plugin reference\n\nold\n${block("- x")}`),
    ).toBeNull();
  });

  test("over every CLAUDE.md of the checkout: the fixed point is the one block splicing leaves the file with", async () => {
    const repo = await loadRepoSnapshot(REPO_ROOT);
    const files = repo
      .under("plugins")
      .filter((rel) => rel.endsWith("/CLAUDE.md"));
    expect(files.length).toBeGreaterThan(100);
    for (const rel of files) {
      const text = (await repo.read(rel))!;
      const fixed = autogenFixedPoint(text);
      if (fixed === null) continue;
      expect(spliceAutogenBlock(text, fixed)).toBe(text);
      // Any other block changes the file.
      expect(spliceAutogenBlock(text, block("- other"))).not.toBe(text);
    }
  });
});
