import { join } from "path";
import { collectCompanionSlots } from "@plugins/plugin-meta/plugins/closure/core";
import type { CompanionSlot } from "@plugins/plugin-meta/plugins/closure/core";
import { buildBarrelFreeTree } from "./barrel-free-tree";

/**
 * Generates the companion manifest: every slot opened to companions, and which
 * plugin provides each of its companions, across the whole repo — into
 * `plugins/framework/plugins/web-sdk/core/companions.generated.ts`, read by the
 * web-sdk at runtime.
 *
 * The closure engine ships a companion wherever its owner ships (or, keyed,
 * wherever its key is used). When the running app nevertheless lacks one — a
 * closure bug, a stale registry, a deferred plugin that never loaded — the
 * owner used to degrade silently: blank icons, slots in registration order, a
 * DataView cell falling back to text. With this manifest the runtime can tell
 * "nothing provides this" (a legitimate fallback) from "a provider exists but
 * this bundle lacks it" (loud). Repo-wide, not per composition: the same answer
 * for every bundle, so the file is committed.
 *
 * Rendered from `collectCompanionSlots` — the same reading the engine's
 * companion edges and usage rules come from, so what the build ships and what
 * the app expects cannot disagree. Barrel-free, and the web-sdk core barrel
 * reaches it at module-load, so it is a pre-barrel manifest. The
 * `companions-in-sync` check fails on drift.
 */

const MANIFEST_REL_PATH =
  "plugins/framework/plugins/web-sdk/core/companions.generated.ts";

const MANIFEST_HEADER = [
  "// DO NOT EDIT — autogenerated by `./singularity build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/companion-manifest-gen.ts).",
  "//",
  "// Every slot opened to companions, keyed by slot id, with the plugins providing",
  "// its companions repo-wide: `always` for a `companions: true` slot, `keyed` (key →",
  "// providers) for a `companions: { key, space }` one. The web-sdk reads it to fail",
  "// loudly when a companion the repo provides is missing from the running bundle.",
  "//",
  "// The `companions-in-sync` check fails on drift.",
].join("\n");

function renderSlot(slot: CompanionSlot): string {
  const id = JSON.stringify(slot.slotId);
  if (!slot.keyed) {
    const plugins = slot.companions.map((c) => JSON.stringify(c.plugin));
    return `  ${id}: { always: [${plugins.join(", ")}] },`;
  }
  const byKey = new Map<string, string[]>();
  for (const c of slot.companions) {
    const list = byKey.get(c.key!) ?? [];
    list.push(c.plugin);
    byKey.set(c.key!, list);
  }
  const keys = [...byKey.keys()].sort();
  const lines = [`  ${id}: {`, "    keyed: {"];
  for (const key of keys)
    lines.push(
      `      ${JSON.stringify(key)}: [${byKey
        .get(key)!
        .map((p) => JSON.stringify(p))
        .join(", ")}],`,
    );
  lines.push("    },", "  },");
  return lines.join("\n");
}

function renderManifest(slots: readonly CompanionSlot[]): string {
  return [
    MANIFEST_HEADER,
    "",
    "export type CompanionManifestEntry =",
    "  | { readonly always: readonly string[] }",
    "  | { readonly keyed: Readonly<Record<string, readonly string[]>> };",
    "",
    "export const companionManifest: Readonly<",
    "  Record<string, CompanionManifestEntry>",
    "> = {",
    ...slots.map(renderSlot),
    "};",
    "",
  ].join("\n");
}

/** Path to the committed manifest file. */
export function companionManifestPath(root: string): string {
  return join(root, MANIFEST_REL_PATH);
}

/** Render the manifest file contents in-memory (used by the in-sync check). */
export async function renderCompanionManifest(root: string): Promise<string> {
  return renderManifest(collectCompanionSlots(await buildBarrelFreeTree(root)));
}
