import { existsSync, readdirSync, rmSync } from "fs";
import { join } from "path";
import {
  APP_SCOPE_DIR,
  resolveGitLayer,
  type ConfigProxy,
  type GitLayerDocument,
} from "@plugins/config_v2/core";
import { asPluginId } from "@plugins/framework/plugins/plugin-id/core";
import {
  COMPOSITION_MODULES_REL,
  compositionConfigLayerFileName,
} from "@plugins/framework/plugins/tooling/plugins/web-artifacts/core";
import { MAIN_COMPOSITION_ID } from "@plugins/infra/plugins/namespace/core";
import { fileConfigProxy, walkJsoncFiles } from "./config-origin-gen";
import { readDefineAppIn } from "./declared-apps";
import {
  collectedDirRegistryPath,
  discoverCollectedDirs,
  listNamedCompositionRegistries,
} from "./plugin-registry-gen";
import { writeGenerated } from "./write-generated";

const ORIGIN_SUFFIX = ".origin.jsonc";

/**
 * What one composition contains, as far as its committed config is concerned:
 * the dot-form ids of its WEB registry's plugins (the demo serve answers only
 * web-registered descriptors, so this is the exact set, not a proxy) and the
 * app ids those plugins declare (an `@app/<id>` scope is kept only for these).
 */
export interface ConfigLayerScope {
  plugins: ReadonlySet<string>;
  apps: ReadonlySet<string>;
}

/**
 * The committed config layer, resolved for the browser and restricted to one
 * composition: storePath (`<hier>/<name>.jsonc`, the key `config-v2.values` is
 * read by) → the descriptor's git-layer document (`resolveGitLayer` — the same
 * rule the build propagates into a user layer with).
 *
 * A pure file walk over `<root>/config` — no descriptor, no barrel. A storePath's
 * `<hier>` IS the plugin the descriptor is stored under (`asPath(pluginId)`), so
 * a document is kept only when that plugin is in `scope.plugins`, and an
 * `@app/<id>` scope only when `<id>` is in `scope.apps` — a composition's build
 * never carries the config of plugins or apps it does not contain.
 *
 * Of what remains, only the documents the committed layer actually ARRANGES are
 * kept: a base that differs from its generated origin (an honored authored
 * override) or any kept `@app` scope. Everything else equals its origin, which
 * codegen generates from the code defaults the browser already holds
 * (backfilled through the descriptor's schema), so shipping it would only add
 * bytes.
 */
export function collectConfigGitLayer(
  root: string,
  scope: ConfigLayerScope,
): Record<string, GitLayerDocument> {
  const configDir = join(root, "config");
  const files: string[] = [];
  walkJsoncFiles(configDir, configDir, files);
  const out: Record<string, GitLayerDocument> = {};
  for (const rel of files.sort()) {
    if (!rel.endsWith(ORIGIN_SUFFIX)) continue;
    if (rel.split("/").includes(APP_SCOPE_DIR)) continue;
    const storePath = `${rel.slice(0, -ORIGIN_SUFFIX.length)}.jsonc`;
    const slash = storePath.lastIndexOf("/");
    const hier = slash < 0 ? "" : storePath.slice(0, slash);
    if (!scope.plugins.has(hier.split("/").join("."))) continue;
    const fileName = storePath.slice(slash + 1);

    const origin = fileConfigProxy(join(configDir, rel));
    const override = fileConfigProxy(join(configDir, storePath));
    const scoped = new Map<string, ConfigProxy>();
    const appDir = join(configDir, hier, APP_SCOPE_DIR);
    if (existsSync(appDir)) {
      for (const entry of readdirSync(appDir, { withFileTypes: true })) {
        if (!entry.isDirectory() || !scope.apps.has(entry.name)) continue;
        scoped.set(
          entry.name,
          fileConfigProxy(join(appDir, entry.name, fileName)),
        );
      }
    }
    const doc = resolveGitLayer(origin, override, scoped);
    if (doc === undefined) continue;
    const originContent = origin.read()?.content;
    const arranged =
      JSON.stringify(doc.base) !== JSON.stringify(originContent) ||
      Object.keys(doc.scopes).length > 0;
    if (arranged) out[storePath] = doc;
  }
  return out;
}

export function renderConfigGitLayer(
  composition: string,
  layer: Record<string, GitLayerDocument>,
): string {
  // A JSON string parsed at load: cheap for tsc and for the JS parser, where a
  // ~250 KB object literal is neither. No import, not even a type one: the file
  // lives outside the plugin tree (`COMPOSITION_MODULES_REL`), where nothing
  // resolves `@plugins/*` for it — config_v2 types the seam itself (its ambient
  // `@composition-config-layer` declaration).
  return `// DO NOT EDIT — generated by \`./singularity build\` (gitignored)
// (see plugins/framework/plugins/tooling/plugins/codegen/core/config-git-layer-gen.ts).
//
// The committed config layer (repo \`config/\`) of composition "${composition}":
// only its own plugins' documents and its own apps' scopes, resolved per
// storePath. Served as the registry artifact's \`config-layer.js\`
// (\`@composition-config-layer\`); a demo scope's browser server answers
// \`config-v2.values\` from it.

export const gitLayer = JSON.parse(
  ${JSON.stringify(JSON.stringify(layer))},
) as Readonly<Record<string, { base: unknown; scopes: Readonly<Record<string, unknown>> }>>;
`;
}

/** The web registries this checkout holds: main's committed one + every resident per-name one. */
function residentWebRegistries(
  root: string,
): Array<{ name: string; file: string }> {
  const webDef = discoverCollectedDirs(root).find((d) => d.dir === "web");
  if (webDef === undefined) {
    throw new Error("config git layer: no `web` collected dir is declared.");
  }
  return [
    { name: MAIN_COMPOSITION_ID, file: collectedDirRegistryPath(webDef) },
    ...listNamedCompositionRegistries(root)
      .filter((r) => r.dir === "web")
      .map(({ name, file }) => ({ name, file })),
  ];
}

/** A web registry's plugins and the apps they declare. */
async function scopeOfRegistry(
  root: string,
  file: string,
): Promise<ConfigLayerScope> {
  const { webEntries } = (await import(file)) as {
    webEntries: Array<{ pluginPath: string; id: string }>;
  };
  const apps = new Set<string>();
  for (const e of webEntries) {
    const app = readDefineAppIn(
      join(root, "plugins", e.pluginPath),
      asPluginId(e.id),
    );
    if (app !== null) apps.add(app.id);
  }
  return { plugins: new Set(webEntries.map((e) => e.id)), apps };
}

/**
 * Emit one config layer per web registry resident in the checkout (build stage
 * 2, after the origins and the seeded overrides) — the registry artifact of
 * each composition then serves its own (`web-artifacts`' composition modules).
 * Stage 1 regenerated exactly this resident set, so no layer is left behind at
 * an older config.
 */
export async function generateConfigGitLayer({
  root,
}: {
  root: string;
}): Promise<void> {
  // The layer's location before 25df26786e moved it under `/.generated/`. That
  // commit also dropped its `.gitignore` line, so a copy an older build left on
  // disk turned into an untracked source file the plugin-doc scan reads
  // (its `ui.tokens.shadow:shadow` made config_v2 a `--shadow` user, and docs
  // drifted on main). Removed here because this generator wrote it; the path is
  // gitignored again so a push cannot commit one. Delete these lines and that
  // `.gitignore` entry once no checkout can still hold one.
  rmSync(join(root, "plugins/config_v2/web/internal/git-layer.generated.ts"), {
    force: true,
  });
  for (const { name, file } of residentWebRegistries(root)) {
    const scope = await scopeOfRegistry(root, file);
    await writeGenerated({
      file: join(
        root,
        COMPOSITION_MODULES_REL,
        compositionConfigLayerFileName(name),
      ),
      content: renderConfigGitLayer(name, collectConfigGitLayer(root, scope)),
    });
  }
}
