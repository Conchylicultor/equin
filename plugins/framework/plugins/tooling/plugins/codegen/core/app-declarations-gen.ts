import { join } from "path";
import { collectWebSlotContributions } from "./web-slot-contributions";

/**
 * Generates the app-declarations manifest: every app the browser registers
 * (`Apps.App`) — its whole `AppRef` (id, name, base path, icon, tile colour,
 * default colour scheme, whether launchers list it)
 * and how it launches (a tab at its base path, or a surface mode with no URL)
 * — as plain data, for the SERVER, which cannot see web slots: the web-app
 * manifest and icon routes (`apps-core/app-manifest`) and the theme's first
 * frame (`ui/theme-engine`) read it.
 *
 * Read off the contributions rather than off `defineApp` source text because
 * the launch kind is the contribution's (`component` vs `surfaceMode`), and
 * because only the bundled set is the set the browser shows. A post-web
 * manifest (see `postWebManifests`): no web barrel may reach it.
 */

const SLOT_IDS = { apps: "apps-core.app" } as const;

// The output mirrors the placeholder committed at this path.
const MANIFEST_REL_PATH = "plugins/apps-core/server/internal/apps.generated.ts";

const MANIFEST_HEADER = [
  "// DO NOT EDIT — autogenerated by `./equin build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/app-declarations-gen.ts).",
  "//",
  "// Every app the browser registers (its Apps.App contributions): the whole AppRef",
  "// and how it launches, as data. Read by the SERVER only; the web runtime reads",
  "// the contributions themselves.",
  "//",
  "// The `app-declarations-in-sync` check fails on drift.",
].join("\n");

interface ProjectedApp {
  app: {
    id: string;
    name: string;
    basePath: string;
    icon: unknown;
    iconColor?: string;
    colorMode?: string;
    listed?: false;
  };
  launch: "tab" | "surface";
}

async function collectAppDeclarations(root: string): Promise<ProjectedApp[]> {
  const { apps } = await collectWebSlotContributions(root, SLOT_IDS);
  return apps
    .map((c): ProjectedApp => {
      const app = c.app as ProjectedApp["app"];
      return {
        app: {
          id: app.id,
          name: app.name,
          basePath: app.basePath,
          icon: app.icon,
          ...(app.iconColor !== undefined && { iconColor: app.iconColor }),
          ...(app.colorMode !== undefined && { colorMode: app.colorMode }),
          ...(app.listed === false && { listed: false as const }),
        },
        launch: c.surfaceMode !== undefined ? "surface" : "tab",
      };
    })
    .sort((a, b) => a.app.id.localeCompare(b.app.id));
}

function renderManifest(apps: readonly ProjectedApp[]): string {
  return [
    MANIFEST_HEADER,
    "",
    'import type { AppDeclaration } from "../../core";',
    "",
    `export const declaredApps: readonly AppDeclaration[] = ${JSON.stringify(apps)};`,
    "",
  ].join("\n");
}

/** Path to the committed manifest file. */
export function appDeclarationsManifestPath(root: string): string {
  return join(root, MANIFEST_REL_PATH);
}

/** Render the manifest file contents in-memory (used by the in-sync check). */
export async function renderAppDeclarationsManifest(
  root: string,
): Promise<string> {
  return renderManifest(await collectAppDeclarations(root));
}
