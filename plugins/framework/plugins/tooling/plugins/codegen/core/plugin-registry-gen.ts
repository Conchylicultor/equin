// ── Entry collection ───────────────────────────────────────────────

export interface CollectedRawEntry {
  pluginPath: string;
  importPath: string;
  id: string;
  /** `@plugins/<path>/core` when the plugin has a core barrel, else null —
   *  rendered only into a `CORE_WARMED_DIRS` registry. */
  coreImportPath: string | null;
}

function hasDefaultExport(text: string): boolean {
  // Mask comments/regex/strings so a commented-out or string-embedded `export
  // default` can't make an entryless barrel look like an entry. These are pure
  // code-construct detectors — the string interior is never read back.
  const src = maskSource(text);
  return (
    /(^|\n)\s*export\s+default\b/.test(src) ||
    /(^|\n)\s*export\s*\{[^}]*\bdefault\b[^}]*\}/.test(src)
  );
}

// ── Registry-generation context ────────────────────────────────────
//
// The plugin tree, its edge graph and the app's own composition are pure
// functions of committed source — IDENTICAL for every collected dir. Build them
// ONCE per generation pass and thread the context through
// `renderCollectedDirRegistry`. This is what keeps registry codegen O(tree)
// instead of O(tree × collectedDirs): there are ~10 collected dirs (web, server,
// central, check, lint, facet, …), so a per-def rebuild meant ~10 full
// 840-plugin tree walks (~12s, the dominant codegen cost). Taking a prebuilt
// context — rather than a `root` the renderer rebuilds from — makes that
// redundant build structurally impossible: the renderer literally cannot trigger
// a tree walk.
export interface RegistryGenContext {
  root: AppPath;
  tree: PluginTree;
  // The cross-plugin edge graph of exactly this `tree`, classified once. Held
  // here so the composition resolution below, and the checks that take a ctx,
  // never re-run `classifyEdges` over the same tree.
  graph: EdgeGraph;
  // What the app ships: the main composition's resolved closure. There
  // is no unfiltered registry — every render says which composition it is for,
  // and this is the answer for the committed `<dir>.generated.ts` files.
  mainBundle: Set<PluginId>;
  // Which composition the committed registries belong to — the main composition, with
  // its resolved home app. Resolved (and validated) once here, alongside
  // `mainBundle`, so every committed render names the same composition.
  main: RegistryComposition;
  // The repo's file set every scan below enumerates and reads — the check's
  // own set when a check built this ctx, else the pass's.
  repo(): Promise<RepoFiles>;
  // Per-`<dir>` scan (the collected entry list plus the raw import-derived
  // dependency graph), memoized for this context's lifetime.
  //
  // Why it is safe to cache HERE rather than anywhere else: a `RegistryGenContext`
  // is a SNAPSHOT of the tree — `tree`, `graph` and `mainBundle` are already
  // source-derived facts frozen at `buildRegistryGenContext` time, and a caller
  // that needs a post-write view of the filesystem must build a fresh ctx to see
  // it. A
  // `<dir>` scan is a pure function of exactly the same inputs (`ctx.tree`,
  // `ctx.repo()`, `dir`) and of nothing else — in particular NOT of the `bundle`,
  // which only filters an already-scanned entry list — so hanging it off the ctx
  // gives it precisely the lifetime it is valid for. Putting it in a
  // module-level cache would instead outlive the snapshot and start answering
  // with a stale filesystem.
  //
  // What it buys: the scan reads every `.ts`/`.tsx` file under every plugin's
  // `<dir>/` tree, which is the expensive half of registry codegen, and the
  // callers that already share ONE ctx re-render the same `<dir>` more than
  // once. `regen-pipeline.ts` shares a ctx between the registry and eager-tier
  // generators (the eager tier re-scanned `web` a second time); the build's
  // stage 1 shares a ctx across every composition one invocation names
  // (N compositions × 3 runtime dirs collapse to 3 scans). Behaviour is
  // unchanged — the cache holds the raw pre-filter scan, so the bundle filter
  // and the dep pruning still run per call. It holds the PROMISE, so two
  // concurrent renders of one `<dir>` share one scan.
  dirScans: Map<string, Promise<DirEntryScan>>;
  // Per browser host (by its declaration path), the inferred graph and the
  // coverage-guarded derivation (`./browser-host-gen.ts`), memoized for this
  // context's lifetime on the same argument as `dirScans`: both are pure
  // functions of the snapshot (the tree, `repo()`'s file set, the committed
  // sources the import closures read). Four callers ask — the generator,
  // `plugins-registry-in-sync`, `browser-host:contributions-covered` and
  // `config-v2:registrations-paired` — and a derivation is seconds of import
  // closures, so ONE ctx pays it once. Promises, like `dirScans`; a rejected
  // one (a guard failure) is every caller's same failure.
  browserHostGraphs: Map<string, BrowserHostGraphMemo>;
  // The coverage guard's reading of `repo()`'s file set
  // (`./browser-host-coverage.ts`): each file read, masked and parsed at most
  // once, and the repo-wide facts every host's scan shares (serving wrappers,
  // every backend barrel's routes, per-plugin descriptor indexes) derived at
  // most once — on the same snapshot argument as `dirScans`. Lazy: only a
  // derivation asks.
  sourceScans(): Promise<SourceScans>;
}

/** One browser host's memoized derivation halves (see `RegistryGenContext.browserHostGraphs`). */
export interface BrowserHostGraphMemo {
  inferred?: Promise<InferredBrowserHostGraph>;
  derived?: Promise<DerivedBrowserHostGraph>;
}

/** The bundle-independent half of `collectEntriesWithDeps`: what one `<dir>`
 *  scan of the tree found, before any bundle filtering. */
interface DirEntryScan {
  allEntries: CollectedRawEntry[];
  rawDeps: Map<string, string[]>;
}

// One ctx per file set (a pass's, or a check's own): see
// `buildRegistryGenContext`.
const contextsByRepo = new WeakMap<RepoFiles, Promise<RegistryGenContext>>();

/**
 * The shared registry-generation context of `pass`. A check passes its own
 * file set as `repo` (so the scans read through it — recorded, for an
 * input-keyed check); omitted, the scans read the pass's set, the one the
 * barrel-free tree was built from.
 *
 * Given a `repo`, the ctx is memoized on it: every check of one run asking
 * with the run's set gets the SAME ctx, so its memos (`dirScans`,
 * `browserHostGraphs`) are paid once per run rather than once per check. That
 * is the ctx's own lifetime argument — a ctx is a snapshot, and a file set is
 * the snapshot it is built over — so the memo never outlives what it
 * describes. (An input-keyed check's recording set is its own object, so it
 * gets its own ctx and every read it makes is recorded.)
 */
export function buildRegistryGenContext(
  pass: CodegenPass,
  repo: RepoFiles = pass.repo,
): Promise<RegistryGenContext> {
  if (repo.root !== pass.root) {
    throw new Error(
      `buildRegistryGenContext(${pass.root}) was handed the file set of ${repo.root}.`,
    );
  }
  let ctx = contextsByRepo.get(repo);
  if (ctx === undefined) {
    ctx = buildContext(pass, repo);
    contextsByRepo.set(repo, ctx);
  }
  return ctx;
}

async function buildContext(
  pass: CodegenPass,
  repo: RepoFiles,
): Promise<RegistryGenContext> {
  const { root } = pass;
  const tree = await buildBarrelFreeTree(pass);
  const graph = classifyEdges(tree);
  const main = resolveMainComposition(graph, root);
  const listing = Promise.resolve(repo);
  const files = (): Promise<RepoFiles> => listing;
  let scans: Promise<SourceScans> | undefined;
  return {
    root,
    tree,
    graph,
    // Throws rather than degrading when main's row is missing or its declared
    // exclusions did not take effect — see `resolveMainComposition`. A registry
    // that contradicts the manifest is worth failing the build for.
    mainBundle: main.bundle,
    main: {
      id: MAIN_COMPOSITION_ID,
      home: resolveRegistryHome(
        tree,
        main.bundle,
        MAIN_COMPOSITION_ID,
        main.home,
      ),
    },
    repo: files,
    dirScans: new Map(),
    browserHostGraphs: new Map(),
    sourceScans: () => (scans ??= files().then(createSourceScans)),
  };
}

/**
 * Every `<dir>` entry in the repo — no composition filter — with the raw
 * cross-plugin `dependsOn` of each. What a generator that picks its own plugin
 * set reads (a browser host's graph, `./browser-host-gen.ts`).
 */
export async function scanCollectedDir(
  ctx: RegistryGenContext,
  dir: string,
): Promise<{
  entries: CollectedRawEntry[];
  deps: ReadonlyMap<string, string[]>;
}> {
  const { allEntries, rawDeps } = await scanDir(ctx, dir);
  return { entries: allEntries, deps: rawDeps };
}

/**
 * The `<dir>` scan for this context, computed on first ask and reused after.
 * See `RegistryGenContext.dirScans` for why a ctx is the right lifetime.
 */
function scanDir(ctx: RegistryGenContext, dir: string): Promise<DirEntryScan> {
  let scan = ctx.dirScans.get(dir);
  if (scan === undefined) {
    scan = computeDirScan(ctx, dir);
    ctx.dirScans.set(dir, scan);
  }
  return scan;
}

async function computeDirScan(
  ctx: RegistryGenContext,
  dir: string,
): Promise<DirEntryScan> {
  const repo = await ctx.repo();
  const allEntries = await collectEntries(ctx.tree, repo, dir);
  const companion = COMPANION_DIRS[dir];
  return {
    allEntries,
    rawDeps: await buildDepsForDir(
      repo,
      allEntries,
      dir,
      companion === undefined
        ? null
        : (await scanDir(ctx, companion)).allEntries,
    ),
  };
}

// ── Companion dirs: a plugin's machine half ────────────────────────
//
// A plugin's `machine/` barrel boots in the SAME plugin graph as every
// `server/` barrel — a desktop backend passes `[...serverEntries,
// ...machineEntries]` to one `bootPluginGraph` — as a node of its own,
// `<pluginPath>#machine` (`machineNode`, plugin-id/core). So the machine
// registry is spelled in node terms: each entry's id is `<id>#machine`, and its
// `dependsOn` names a machine node `x#machine` for an `@plugins/x/machine`
// import, the server node `x` for any other import of plugin `x`, and — always
// — its own plugin's server node, so a machine half's hooks run after its
// server half's.
//
// The map says which dir's graph a companion dir's entries join.
const COMPANION_DIRS: Readonly<Partial<Record<string, string>>> = {
  machine: "server",
};

// The registries whose entries also carry their plugin's core-barrel loader
// (`core`): the backend's load waves warm a wave's core barrels before its
// server barrels (server-core's `boot-stages.ts` says why), and central's
// before its central barrels (central-core's `bin/index.ts`). A literal
// `import()` per entry, so the boot reaches each barrel by a path the source
// digest follows — never by a path computed from `pluginPath`.
const CORE_WARMED_DIRS: ReadonlySet<string> = new Set([
  "server",
  "machine",
  "central",
]);

/** The graph node a `<dir>` entry of `pluginPath` boots as. */
function nodeKeyFor(dir: string, pluginPath: string): string {
  return COMPANION_DIRS[dir] === undefined
    ? pluginPath
    : machineNode(pluginPath);
}

/**
 * A collected-dir folder name as a JavaScript identifier: `data-dirs` →
 * `dataDirs`, so the emitted registry const is `dataDirsEntries`.
 *
 * Interpolating the folder name raw was fine only because every collected dir
 * happened to be one lowercase word (`check`, `facet`, `exhibits`). The first
 * hyphenated one emitted `export const data-dirsEntries`, which is not a legal
 * identifier — so the generated file failed to PARSE, and the failure surfaced
 * far from here, as a facet-extraction `AggregateError` during doc generation.
 * Deriving the identifier is what makes a hyphenated collected dir
 * representable at all, rather than a trap the next one falls into too.
 */
function identifierForDir(dir: string): string {
  return dir.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

// Per-file scans, cached as file records (`file-scans.ts`).
const SCANNER_MODULE =
  "plugins/framework/plugins/tooling/plugins/codegen/core/plugin-registry-gen.ts";
const DEFAULT_EXPORT_SCAN: FileScan<boolean> = {
  module: SCANNER_MODULE,
  params: ["default-export"],
  scan: (src) => hasDefaultExport(src),
};
const IMPORT_SPECIFIER_SCAN: FileScan<string[]> = {
  module: SCANNER_MODULE,
  params: ["import-specifiers"],
  scan: (src) => findImports(src).map((imp) => imp.specifier),
};

const LEAF_FOLDER_SET: ReadonlySet<string> = new Set(LEAF_FOLDERS);

// Which `<dir>/index.ts` files are entries. A LEAF folder (`check/`, `lint/`,
// `facet/`, …) is never imported — its `index.ts` exists only to be collected —
// so every one is an entry, by construction, and its loader fails loudly if it
// has no default export. Only a BARREL folder (`cli/`, `web/`, …) can hold an
// `index.ts` that is not a contribution (shared machinery other plugins import),
// so only there is the default export scanned for. A leaf entry used to be
// scanned too, and a masker that lost sync on a nested template literal read
// server-core's `export default` as string: its check vanished from the
// registry and never ran.
async function collectEntries(
  tree: PluginTree,
  repo: RepoFiles,
  dir: string,
): Promise<CollectedRawEntry[]> {
  const barrels = [...tree.byDir.values()]
    .map((node) => ({ node, rel: `plugins/${node.path}/${dir}/index.ts` }))
    .filter((b) => repo.has(b.rel));
  const isEntry = LEAF_FOLDER_SET.has(dir)
    ? barrels.map(() => true)
    : await scanFiles(
        repo,
        barrels.map((b) => b.rel),
        DEFAULT_EXPORT_SCAN,
      );
  const entries: CollectedRawEntry[] = [];
  for (const [i, { node }] of barrels.entries()) {
    if (!isEntry[i]) continue;
    entries.push({
      pluginPath: node.path,
      importPath: `@plugins/${node.path}/${dir}`,
      id: node.id,
      coreImportPath: repo.has(`plugins/${node.path}/core/index.ts`)
        ? `@plugins/${node.path}/core`
        : null,
    });
  }
  entries.sort((a, b) => a.importPath.localeCompare(b.importPath));
  return entries;
}

// ── Dependency graph ───────────────────────────────────────────────

const TS_FILE_RE = /\.tsx?$/;

// Every shipping `.ts`/`.tsx` under a plugin's `<dir>/` tree, skipping
// `node_modules`, nested `plugins/` (each sub-plugin is scanned as its own
// entry) and test code (`isTestCodePath`). A test's imports are not the
// plugin's: counting them made every plugin whose suite uses `createTestDb`
// "depend on" db-test-fixture at runtime, and put test-only npm packages in the
// vendor set.
function tsFilesUnder(repo: RepoFiles, base: string): string[] {
  return repo.under(base).filter((rel) => {
    const segments = rel.slice(base.length + 1).split("/");
    return (
      TS_FILE_RE.test(segments.at(-1)!) &&
      !segments.some((s) => s === "node_modules" || s === "plugins") &&
      !isTestCodePath(segments)
    );
  });
}

// Every import specifier found in a plugin's `<dir>/` tree. `findImports` masks
// comments/regex/strings and reads each specifier back by offset, so an import
// written inside a string/comment can't register a phantom dependency edge.
// Covers both `import … from` and `export … from`.
async function collectImportSpecifiers(
  repo: RepoFiles,
  pluginPath: string,
  dir: string,
  tick: () => Promise<void>,
): Promise<Set<string>> {
  const files = tsFilesUnder(repo, `plugins/${pluginPath}/${dir}`);
  const specifiers = new Set<string>();
  for (const found of await scanFiles(repo, files, IMPORT_SPECIFIER_SCAN)) {
    for (const spec of found) specifiers.add(spec);
    await tick();
  }
  return specifiers;
}

/** True for npm-style bare specifiers (neither relative/absolute, `@plugins/*`, nor a composition module). */
function isBareNpmSpecifier(mod: string): boolean {
  return (
    !mod.startsWith(".") &&
    !mod.startsWith("/") &&
    !mod.startsWith("@plugins/") &&
    !COMPOSITION_SPECIFIERS.has(mod)
  );
}

/**
 * Bare npm specifiers (per subpath: `react-dom/client` ≠ `react-dom`) imported
 * by each collected plugin's `<dir>/` tree — the source-level vendor-set input
 * for the web-artifacts engine (and its Phase-2 `map-in-sync` cross-check).
 * Node builtins (`node:*`) are included verbatim; consumers filter. Does NOT
 * change the emitted registry shape.
 */
export async function collectBareSpecifiers(
  ctx: RegistryGenContext,
  dir: string,
): Promise<Map<string, string[]>> {
  const repo = await ctx.repo();
  const { allEntries } = await scanDir(ctx, dir);
  const tick = timeSlicer();
  const out = new Map<string, string[]>();
  for (const e of allEntries) {
    const specifiers = await collectImportSpecifiers(
      repo,
      e.pluginPath,
      dir,
      tick,
    );
    const bare = [...specifiers].filter(isBareNpmSpecifier).sort();
    if (bare.length > 0) out.set(e.pluginPath, bare);
  }
  return out;
}

async function buildDepsForDir(
  repo: RepoFiles,
  entries: CollectedRawEntry[],
  dir: string,
  // The companion graph's entries (`COMPANION_DIRS`) — the server entries a
  // machine entry may depend on — or null for a dir that is its own graph.
  companionEntries: CollectedRawEntry[] | null,
): Promise<Map<string, string[]>> {
  const pluginPrefix = (e: CollectedRawEntry) =>
    e.importPath.slice(0, e.importPath.lastIndexOf("/"));
  const prefixToPluginPath = new Map<string, string>();
  for (const e of entries)
    prefixToPluginPath.set(pluginPrefix(e), e.pluginPath);
  const companionPaths = new Map<string, string>();
  for (const e of companionEntries ?? [])
    companionPaths.set(pluginPrefix(e), e.pluginPath);
  const companionPathSet = new Set(companionPaths.values());

  const tick = timeSlicer();
  const gate = createSemaphore(PLUGIN_SCAN_WIDTH);
  const result = new Map<string, string[]>();
  await Promise.all(
    entries.map((e) =>
      gate.run(async () => {
        const deps = new Set<string>();
        if (companionEntries === null) {
          for (const mod of await collectImportSpecifiers(
            repo,
            e.pluginPath,
            dir,
            tick,
          )) {
            if (!mod.startsWith("@plugins/")) continue;
            const lastSlash = mod.lastIndexOf("/");
            if (lastSlash <= 0) continue;
            const depPath = prefixToPluginPath.get(mod.slice(0, lastSlash));
            if (depPath && depPath !== e.pluginPath) deps.add(depPath);
          }
        } else {
          // A machine half always runs after its own server half.
          if (companionPathSet.has(e.pluginPath)) deps.add(e.pluginPath);
          for (const mod of await collectImportSpecifiers(
            repo,
            e.pluginPath,
            dir,
            tick,
          )) {
            if (!mod.startsWith("@plugins/")) continue;
            const lastSlash = mod.lastIndexOf("/");
            if (lastSlash <= 0) continue;
            const prefix = mod.slice(0, lastSlash);
            const machinePath =
              mod.slice(lastSlash + 1) === dir
                ? prefixToPluginPath.get(prefix)
                : undefined;
            if (machinePath !== undefined) {
              if (machinePath !== e.pluginPath)
                deps.add(nodeKeyFor(dir, machinePath));
              continue;
            }
            const serverPath = companionPaths.get(prefix);
            if (serverPath !== undefined) deps.add(serverPath);
          }
        }
        if (deps.size > 0) result.set(e.pluginPath, [...deps].sort());
      }),
    ),
  );
  return result;
}

// ── Filtered entries + pruned deps ─────────────────────────────────
//
// There is exactly ONE filter, and it is REQUIRED: a registry is the registry of
// some composition, so "render this registry without saying which composition it
// is for" has no spelling. `generatePluginRegistry` passes `ctx.mainBundle` at
// the call site where that question is asked; a composition build passes its own.
// Each surviving entry's `dependsOn` is pruned to the surviving `pluginPath`s: a
// dangling dep on a non-emitted plugin would break the loader's topo-sort (a hard
// closure's deps already survive, so this is defensive). Shared by
// `renderCollectedDirRegistry` (so its output is byte-identical) AND the
// eager-tier generator, which needs the exact same filtered web entry set +
// pruned `dependsOn` graph.
export async function collectEntriesWithDeps(
  ctx: RegistryGenContext,
  dir: string,
  // The composition's bundle: the dot-form PluginId set of its hard closure.
  bundle: Set<string>,
): Promise<{ entries: CollectedRawEntry[]; deps: Map<string, string[]> }> {
  const { allEntries, rawDeps } = await scanDir(ctx, dir);
  const entries = allEntries.filter((e) => bundle.has(e.id));
  // Surviving graph NODES: this dir's own, plus — for a companion dir — the
  // surviving entries of the graph it joins.
  const survivingPaths = new Set(
    entries.map((e) => nodeKeyFor(dir, e.pluginPath)),
  );
  const companion = COMPANION_DIRS[dir];
  if (companion !== undefined) {
    for (const e of (await scanDir(ctx, companion)).allEntries) {
      if (bundle.has(e.id)) survivingPaths.add(e.pluginPath);
    }
  }
  const deps = new Map<string, string[]>();
  for (const e of entries) {
    const entryDeps = (rawDeps.get(e.pluginPath) ?? []).filter((d) =>
      survivingPaths.has(d),
    );
    if (entryDeps.length > 0) deps.set(e.pluginPath, entryDeps);
  }
  return { entries, deps };
}

// ── Renderer ───────────────────────────────────────────────────────

export async function renderCollectedDirRegistry(opts: {
  ctx: RegistryGenContext;
  def: DiscoveredCollectedDir;
  // Which composition this registry belongs to: a `composition`-membership
  // registry exports it (`composition = { id, home }`), so the runtime knows
  // what it was deployed as — the web shell's `/` redirect reads `home` from it
  // with no request. A `checkout` dir belongs to no composition and ignores it.
  composition: RegistryComposition;
  // REQUIRED: which composition this registry is for — the dot-form PluginId set
  // of its hard closure. Pass `ctx.mainBundle` for the committed
  // `<dir>.generated.ts` files. Required rather than optional because an
  // unfiltered render would be a registry belonging to no composition, which is
  // how the app's membership and the manifest's used to drift apart silently.
  bundle: Set<string>;
}): Promise<string> {
  const { ctx, def, bundle } = opts;
  const { entries, deps } = await collectEntriesWithDeps(ctx, def.dir, bundle);
  return renderRegistry(
    def.dir,
    entries,
    deps,
    def.membership === "composition" ? opts.composition : null,
  );
}

/**
 * `<dir>`'s registry for a composition holding no plugin with that folder —
 * the shape every importer of the registry reads, listing nothing. What a
 * check bundles in place of the composition-dependent part of an entrypoint,
 * so it measures the part no composition can shrink.
 */
export function renderEmptyCollectedDirRegistry(
  dir: string,
  composition: RegistryComposition,
): string {
  return renderRegistry(dir, [], new Map(), composition);
}

/**
 * The composition a registry belongs to, as the runtime reads it back from the
 * registry module's `composition` export.
 */
export interface RegistryComposition {
  id: string;
  /** The app owning bare `/` — a `defineApp` id; null when the bundle holds no app. */
  home: string | null;
}

// The apps a tree declares, per tree. `readDeclaredApps` reads every plugin's
// `core/` from disk (~0.5 s), and one ctx resolves several homes against one
// tree — main's, each named composition's, each browser host's. A tree is a
// snapshot (`buildBarrelFreeTree` memoizes it per pass), so the answer lives
// exactly as long as the tree it was read for.
const declaredAppsByTree = new WeakMap<PluginTree, Map<string, DeclaredApp>>();

function declaredAppsOf(tree: PluginTree): Map<string, DeclaredApp> {
  let apps = declaredAppsByTree.get(tree);
  if (apps === undefined) {
    apps = readDeclaredApps(tree);
    declaredAppsByTree.set(tree, apps);
  }
  return apps;
}

/**
 * A composition's manifest `home`, resolved against its bundle — THROWS on any
 * invalid home (missing, not an app, not bundled), so no build, `--skip-checks`
 * included, can emit a registry whose `/` lands on the wrong app or none.
 * `composition-closure` reports the same `resolveCompositionHome` verdict.
 */
export function resolveRegistryHome(
  tree: PluginTree,
  bundle: ReadonlySet<string>,
  name: string,
  home: string,
): string | null {
  // Building a composition's registries IS deploying it: something must own `/`.
  const r = resolveCompositionHome({
    apps: declaredAppsOf(tree),
    bundle,
    home,
    deployed: true,
  });
  if (r.kind === "error") {
    throw new Error(
      `Composition "${name}" ${r.message} ` +
        `(plugins/plugin-meta/plugins/composition/core/config.ts, or the Studio compositions pane).`,
    );
  }
  return r.kind === "app" ? r.appId : null;
}

function renderRegistry(
  dir: string,
  entries: CollectedRawEntry[],
  deps: Map<string, string[]>,
  composition: RegistryComposition | null,
): string {
  const exportName = `${identifierForDir(dir)}Entries`;

  const lines: string[] = [];
  lines.push(HEADER);
  lines.push("");
  lines.push("export interface CollectedEntry {");
  lines.push("  pluginPath: string;");
  lines.push("  id: string;");
  lines.push("  loader: () => Promise<{ default: unknown }>;");
  lines.push("  dependsOn: string[];");
  const warmsCore = CORE_WARMED_DIRS.has(dir);
  if (warmsCore) lines.push("  core: (() => Promise<unknown>) | null;");
  lines.push("}");
  lines.push("");
  lines.push(`export const ${exportName}: CollectedEntry[] = [`);
  for (const e of entries) {
    const entryDeps = deps.get(e.pluginPath) ?? [];
    const depsLiteral =
      entryDeps.length > 0
        ? `[${entryDeps.map((d) => JSON.stringify(d)).join(", ")}]`
        : "[]";
    const id = COMPANION_DIRS[dir] === undefined ? e.id : machineNode(e.id);
    const core = !warmsCore
      ? ""
      : e.coreImportPath === null
        ? ", core: null"
        : `, core: () => import(${JSON.stringify(e.coreImportPath)})`;
    lines.push(
      `  { pluginPath: ${JSON.stringify(e.pluginPath)}, id: ${JSON.stringify(id)}, loader: () => import(${JSON.stringify(e.importPath)}), dependsOn: ${depsLiteral}${core} },`,
    );
  }
  lines.push("];");
  if (composition !== null) {
    lines.push("");
    lines.push("export interface CompositionIdentity {");
    lines.push("  id: string;");
    lines.push("  home: string | null;");
    lines.push("}");
    lines.push("");
    lines.push(
      `export const composition: CompositionIdentity = { id: ${JSON.stringify(composition.id)}, home: ${JSON.stringify(composition.home)} };`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

// ── Public API ─────────────────────────────────────────────────────

/**
 * The plugin set `def`'s COMMITTED registry lists: the main
 * composition's closure for a `composition` dir, every plugin the checkout
 * declares for a `checkout` one (see `CollectedDirMembership`). The one answer
 * the generator and `plugins-registry-in-sync` both render with.
 */
export function committedRegistryBundle(
  ctx: RegistryGenContext,
  def: DiscoveredCollectedDir,
): Set<string> {
  return def.membership === "checkout"
    ? new Set([...ctx.tree.byDir.values()].map((n) => n.id))
    : ctx.mainBundle;
}

export async function generatePluginRegistry({
  ctx,
}: {
  // The pass's context, so the pipeline shares ONE tree walk between the
  // registry and eager-tier generators (both are pure functions of the same
  // barrel-free tree).
  ctx: RegistryGenContext;
}): Promise<void> {
  const defs = await discoverCollectedDirsIn(await ctx.repo());
  for (const def of defs) {
    await writeGenerated({
      file: collectedDirRegistryPath(def),
      // The committed runtime registries ARE the main composition's
      // registries — `compositionRegistryFileName` says so, and this is where
      // that is made true rather than merely asserted afterwards. A `checkout`
      // dir (source metadata, e.g. `guard`) lists every plugin instead.
      content: await renderCollectedDirRegistry({
        ctx,
        def,
        bundle: committedRegistryBundle(ctx, def),
        composition: ctx.main,
      }),
    });
  }
}

export async function generateCompositionRegistry(opts: {
  bundle: Set<string>;
  /**
   * The composition id these registries belong to. REQUIRED: every filtered
   * registry is keyed by name, so no producer can write a checkout-global one.
   */
  name: string;
  /** The manifest's declared `home`, resolved against `bundle` (throws when invalid). */
  home: string;
  // The pass's context (`buildRegistryGenContext`, memoized per pass), so one
  // build shares ONE tree walk across several compositions' registries.
  ctx: RegistryGenContext;
}): Promise<void> {
  assertCompositionName(opts.name);
  // The main composition's registry is the COMMITTED `<dir>.generated.ts`
  // (`compositionRegistryFileName`), which `generatePluginRegistry` already
  // wrote this build. Writing a `<dir>.composition.<main>.generated.ts`
  // beside it would mint a second, gitignored spelling of the same registry —
  // the file that used to reconfigure main's backend on its next spawn purely by
  // being present, and the reason a hermetic build of the main composition was
  // refused. Nothing may produce it, so the skip is here, at the one writer,
  // rather than as a guard at each caller.
  if (opts.name === MAIN_COMPOSITION_ID) return;
  const { ctx } = opts;
  const composition: RegistryComposition = {
    id: opts.name,
    home: resolveRegistryHome(ctx.tree, opts.bundle, opts.name, opts.home),
  };
  const defs = await discoverCollectedDirsIn(await ctx.repo());
  for (const def of defs) {
    if (!COMPOSITION_RUNTIME_DIRS.has(def.dir)) continue;
    await writeGenerated({
      file: collectedDirNamedCompositionRegistryPath(def, opts.name),
      content: await renderCollectedDirRegistry({
        ctx,
        def,
        bundle: opts.bundle,
        composition,
      }),
    });
  }
  // The backend that boots those registries: its serving entry, written last
  // so it never names a registry not yet on disk.
  await writeGenerated({
    file: backendEntryPath(ctx.root, opts.name),
    content: renderBackendEntry(opts.name),
  });
}

/** The serving entry of `composition`'s backend in the checkout at `root`. */
function backendEntryPath(root: AppPath, composition: string): AppPath {
  return joinAppPath(root, SERVER_CORE_RELATIVE, backendEntryFor(composition));
}

/**
 * The serving entry of `composition`'s backend (`backendEntryFor`, in
 * `infra/paths`): imports the composition's server and machine registries by
 * LITERAL path and hands them to server-core's `bin/serve.ts`. The main
 * composition's render IS the committed `bin/index.ts` — held byte-identical by
 * `server-core:backend-entry-in-sync`, which is also what puts this template in
 * front of tsc; any other composition's is gitignored, written by
 * `generateCompositionRegistry` beside its filtered registries.
 *
 * Why a file per composition rather than one entry that picks its registry: a
 * pick is an import by a computed path, and the code a backend runs must be a
 * closure `sourceDigest` can follow (research/2026-11-05-global-backend-code-identity.md).
 */
export function renderBackendEntry(composition: string): string {
  const registry = (dir: string) =>
    `../core/${compositionRegistryFileName(dir, composition).replace(/\.ts$/, "")}`;
  return [
    "// DO NOT EDIT — a composition backend's serving entry, rendered by codegen's",
    "// `renderBackendEntry` (plugins/framework/plugins/tooling/plugins/codegen/core/plugin-registry-gen.ts).",
    "// The main composition's is the committed `bin/index.ts`, held equal to the",
    "// render by `server-core:backend-entry-in-sync`; any other composition's is the",
    "// gitignored `bin/index.composition.<id>.generated.ts` its build writes.",
    "//",
    "// Its registries are imported by LITERAL path, so the code this backend runs is",
    "// a closure `sourceDigest` can follow. WHICH app it is was decided by the entry",
    "// the spec's `command` runs (`backendEntryFor`, infra/paths); `serve` checks",
    "// that against the spec's `composition` before it binds anything.",
    "",
    "// FIRST, and it must stay first: this declares the namespace this backend",
    "// serves, from the `--namespace` the gateway spawned it with. Everything below",
    "// reads that answer, and modules in the closure resolve it at module eval",
    "// (`config_v2`'s config dir), so an import above this line boots the process",
    "// without an identity. See `./declare-namespace`.",
    'import "./declare-namespace";',
    'import "./pin-toolchain";',
    `import * as server from "${registry("server")}";`,
    `import * as machine from "${registry("machine")}";`,
    'import { serve } from "./serve";',
    "",
    "await serve({ server, machine });",
    "",
  ].join("\n");
}
