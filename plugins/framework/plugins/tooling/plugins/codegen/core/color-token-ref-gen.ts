import { writeGenerated } from "./write-generated";
import { collectTokenGroups } from "./token-group-vars-gen";

/**
 * Generates `ColorTokenRef` — the string-literal union of every CSS var the
 * colour PALETTE token groups declare — into the zero-import leaf
 * `ui/tokens/color-ref`.
 *
 * Why generated rather than derived (`TokenVarOf<typeof group>`): deriving it
 * imports the token-group descriptors, which import theme-engine, which reaches
 * config_v2 and network/live — while network/live (`LiveFieldOption.tint`),
 * data-view (`FieldOption.tint`) and Sonata need the type BELOW all of that. A
 * generated literal union carries the same closed set with no import edge.
 *
 * The vars are read from the real descriptors (`collectTokenGroups`, the same
 * single pass the token-group-vars manifest uses), so a renamed or added token
 * lands in the union on the next build; the `color-token-ref-in-sync` check
 * fails on drift.
 */

/**
 * The palettes a value may be tinted from — THE one place this closed list
 * lives: the app palette (status and accent colours), the categorical series,
 * the chart ramp and the chord colours (Sonata's per-source tints). Adding a
 * palette here is a deliberate widening of every tint.
 */
export const COLOR_TOKEN_REF_GROUPS = [
  "color-palette",
  "categorical",
  "chart",
  "chord-palette",
] as const;

const COLOR_TOKEN_REF_REL_PATH =
  "plugins/ui/plugins/tokens/plugins/color-ref/core/color-token-ref.generated.ts";

const HEADER = [
  "// DO NOT EDIT — autogenerated by `./equin build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/color-token-ref-gen.ts).",
  "//",
  "// The `color-token-ref-in-sync` check fails on drift.",
].join("\n");

const DOC = [
  "/**",
  ' * A reference to a DECLARED colour token — its CSS var (`"--categorical-3"`,',
  ' * `"--success"`), drawn as `var(<ref>)`. The union of every var the palette',
  ` * token groups (${COLOR_TOKEN_REF_GROUPS.join(", ")}) declare, so a tint`,
  " * naming a colour no palette declares is a tsc error, and a theme that",
  " * re-colours the token re-colours every tint that names it.",
  " */",
].join("\n");

/** Path to the committed generated file. */
export function colorTokenRefPath(root: string): string {
  return `${root}/${COLOR_TOKEN_REF_REL_PATH}`;
}

/** Render the generated file contents in-memory (used by the in-sync check). */
export async function renderColorTokenRef(root: string): Promise<string> {
  const groups = await collectTokenGroups(root);
  const vars = new Set<string>();
  for (const id of COLOR_TOKEN_REF_GROUPS) {
    const group = groups[id];
    if (!group) {
      throw new Error(
        `color-token-ref: palette token group "${id}" (COLOR_TOKEN_REF_GROUPS) is not registered by any web barrel`,
      );
    }
    for (const v of group.vars) vars.add(v);
  }
  const sorted = [...vars].sort((a, b) => a.localeCompare(b));
  return [
    HEADER,
    "",
    DOC,
    "export type ColorTokenRef =",
    ...sorted.map(
      (v, i) => `  | ${JSON.stringify(v)}${i === sorted.length - 1 ? ";" : ""}`,
    ),
    "",
  ].join("\n");
}

/** Regenerate `color-token-ref.generated.ts` if it drifted. */
export async function generateColorTokenRef(opts: {
  root: string;
}): Promise<void> {
  await writeGenerated({
    file: colorTokenRefPath(opts.root),
    content: await renderColorTokenRef(opts.root),
  });
}
