import {
  joinAppPath,
  type AppPath,
} from "@plugins/infra/plugins/host-fs/plugins/user-path/core";
import { join, relative } from "path";
import { writeGenerated } from "./write-generated";
import { sourceFilesIn } from "@plugins/plugin-meta/plugins/parse-utils/core";
import { buildBarrelFreeTree } from "./barrel-free-tree";
import { mainBundle } from "./main-bundle";
import { scanFiles } from "./file-scans";
import { DATA_VIEW_SCAN } from "./data-views.scan";
import type { CodegenPass } from "./codegen-pass";

/**
 * Generates the data-views manifest consumed by the data-view primitive: the
 * complete set of `defineDataView("<id>")` ids scraped from every plugin's
 * `web/**` source.
 *
 * Like reorder's reorderable-slots manifest, this is a pure-data bridge from
 * build-time (which can see web-only marker calls) to both runtimes: the
 * data-view barrels read `dataViews` and register one config_v2 descriptor per
 * id. Each entry carries the *defining* plugin's id (the node whose `web/**`
 * contains the `defineDataView("<id>")` marker), so the descriptor registers
 * under `config/<pluginId>/<id>.jsonc` — the consuming plugin's tree, exactly as
 * reorder plants each slot's directive under its defining plugin.
 *
 * The `data-views-in-sync` check fails on drift.
 */

// The output mirrors the placeholder committed at
// plugins/primitives/plugins/data-view/shared/data-views.generated.ts.
const MANIFEST_REL_PATH =
  "plugins/primitives/plugins/data-view/shared/data-views.generated.ts";

const MANIFEST_HEADER = [
  "// DO NOT EDIT — autogenerated by `./equin build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/data-views-gen.ts).",
  "//",
  '// Every `defineDataView("<id>")` marker call found in any plugin\'s web/**',
  "// source. The data-view primitive registers one config_v2 descriptor per id",
  "// on both runtimes from this manifest. Each entry's `pluginId` is the",
  "// *defining* plugin's id (its tree path), so the descriptor registers under",
  "// `config/<pluginId>/<id>.jsonc` — the consuming plugin's tree.",
  "//",
  "// The `data-views-in-sync` check fails on drift.",
].join("\n");

export interface DataViewEntry {
  id: string;
  /** Hierarchy id of the plugin whose web/** owns the `defineDataView` marker. */
  pluginId: string;
}

/**
 * Walk the plugin tree (barrel-free static scan) and collect every
 * `defineDataView("<id>")` id keyed to its DEFINING plugin (the node whose
 * `web/**` owns the marker). Each file is FULL-masked once (so a
 * `defineDataView("x")` written inside a comment, string or template literal is
 * never mistaken for a real marker) and every id is read back from the ORIGINAL
 * by offset. Deduped by id (FIRST definer wins, stable since `tree.byDir`
 * iteration is deterministic) and sorted by id.
 *
 * THROWS on a `defineDataView` call whose id is not statically resolvable. The
 * manifest is the only thing that registers a data view's config descriptor, so
 * an id this scanner cannot read is lost capability, not a tolerable gap —
 * dropping it silently would leave a data view with no persisted view state and
 * nothing anywhere saying why.
 *
 * Uses the barrel-free tree: this collector only reads `node.dir` /
 * `node.id` and text-scans web source — it never touches facets/barrel data, so
 * a barrel-free tree is correct. Critically, it MUST stay barrel-free: the
 * manifest it feeds is imported by plugin barrels at module-load, so it has to
 * be regenerated BEFORE the first barrel import freezes the ESM cache.
 */
export async function collectDataViews(
  pass: CodegenPass,
): Promise<DataViewEntry[]> {
  const { root } = pass;
  const tree = await buildBarrelFreeTree(pass);
  // A plugin the app's composition does not bundle never registers its data-view
  // descriptor at runtime (its barrel is omitted from the registry), so emitting
  // its `config/<pluginId>/` origin would orphan user overrides under
  // `pruneOrphanedConfigFiles`. Filter by membership — the data-view descriptor
  // is a config_v2 origin keyed by the DEFINING plugin, exactly the orphan-prune
  // hazard.
  const bundle = mainBundle(tree, root);
  const definingPath = new Map<string, string>();

  // Each file's data-view ids are a file record: only a file whose blob
  // changed is read and scanned.
  const owned: { file: string; pluginId: string }[] = [];
  for (const node of tree.byDir.values()) {
    if (!bundle.has(node.id)) continue;
    for (const file of sourceFilesIn(tree.repo, join(node.dir, "web")))
      owned.push({ file: relative(root, file), pluginId: node.id });
  }
  const found = await scanFiles(
    tree.repo,
    owned.map((o) => o.file),
    DATA_VIEW_SCAN,
  );
  owned.forEach(({ pluginId }, i) => {
    for (const id of found[i]!) {
      if (!definingPath.has(id)) definingPath.set(id, pluginId);
    }
  });

  return [...definingPath.entries()]
    .map(([id, pluginId]) => ({ id, pluginId }))
    .sort((a, b) => a.id.localeCompare(b.id));
}

function renderManifest(entries: DataViewEntry[]): string {
  const lines: string[] = [];
  lines.push(MANIFEST_HEADER);
  lines.push("");
  lines.push("export interface DataViewEntry {");
  lines.push("  id: string;");
  lines.push("  pluginId: string;");
  lines.push("}");
  lines.push("");
  if (entries.length === 0) {
    lines.push("export const dataViews: DataViewEntry[] = [];");
  } else {
    lines.push("export const dataViews: DataViewEntry[] = [");
    for (const e of entries) {
      lines.push(
        `  { id: ${JSON.stringify(e.id)}, pluginId: ${JSON.stringify(e.pluginId)} },`,
      );
    }
    lines.push("];");
  }
  lines.push("");
  return lines.join("\n");
}

/** Path to the committed manifest file. */
export function dataViewsManifestPath(root: AppPath): AppPath {
  // `root`: the checkout root the caller works in.
  return joinAppPath(root, MANIFEST_REL_PATH);
}

/** Render the manifest file contents in-memory (used by the in-sync check). */
export async function renderDataViewsManifest(
  pass: CodegenPass,
): Promise<string> {
  const entries = await collectDataViews(pass);
  return renderManifest(entries);
}

/** Regenerate `data-views.generated.ts` if it drifted. */
export async function generateDataViews(opts: {
  pass: CodegenPass;
}): Promise<void> {
  await writeGenerated({
    file: dataViewsManifestPath(opts.pass.root),
    content: await renderDataViewsManifest(opts.pass),
  });
}
