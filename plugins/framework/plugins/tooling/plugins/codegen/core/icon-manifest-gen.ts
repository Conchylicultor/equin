import {
  joinAppPath,
  type AppPath,
} from "@plugins/infra/plugins/host-fs/plugins/user-path/core";
import { relative } from "path";
import { sourceFilesIn } from "@plugins/plugin-meta/plugins/parse-utils/plugins/source-files/core";
import { buildBarrelFreeTree } from "./barrel-free-tree";
import { scanFiles } from "./file-scans";
import type { IconManifest } from "./icon-manifest.scan";
import type { CodegenPass } from "./codegen-pass";

/**
 * Generates the icon manifest — every icon name the code draws, collected from
 * its `symbol("…")` / `brand("…")` / `seti("…")` calls, read from each file's
 * syntax tree (every reference to an imported constructor, `icon-manifest.scan.ts`) — into
 * `plugins/ui/plugins/icons/plugins/sprites/machine/internal/icon-manifest.generated.ts`,
 * next to the sprite builder, its only reader. (Not in the icons `core/`:
 * the CLI loads that barrel — through the icons checks — in the same process
 * that regenerates this file, which would freeze the stale copy.)
 *
 * The sprite server ships exactly these names, so an icon costs bytes only once
 * some code names it. The `icons/literal-icon-name` lint keeps every use a
 * direct call with a string literal; the scan follows every reference to the
 * imported binding and throws on any other use, so a name cannot be missed by
 * how its call is written (a spread, an argument) — never an empty box.
 *
 * Only files importing the icon constructors are read — by the barrel alias or
 * by a relative path from inside the icons plugin (`isIconRefModule`, the same
 * resolution the icons lint rules use) — so an unrelated `symbol(…)` elsewhere
 * is never collected, and no spelling of the import hides a file from the scan. Barrel-free (a plain file walk), so
 * it is registered as a pre-barrel manifest: the sprites server barrel reaches
 * the file at module-load. The `icons:manifest-in-sync` check fails on drift.
 */

const MANIFEST_REL_PATH =
  "plugins/ui/plugins/icons/plugins/sprites/machine/internal/icon-manifest.generated.ts";

const MANIFEST_HEADER = [
  "// DO NOT EDIT — autogenerated by `./equin build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/icon-manifest-gen.ts).",
  "//",
  '// Every `symbol("…")` / `brand("…")` / `seti("…")` literal in a file importing the icon',
  "// constructors. The sprite server draws exactly these names.",
  "//",
  "// The `icons:manifest-in-sync` check fails on drift.",
].join("\n");

/** Every icon name the repo draws, scanned from source now (not read from the generated file). */
export async function collectIconManifest(
  pass: CodegenPass,
): Promise<IconManifest> {
  const { root } = pass;
  const symbols = new Set<string>();
  const brands = new Set<string>();
  const seti = new Set<string>();
  // Every plugin's own files (a walk stops at `plugins/`, where each child is
  // its own node). Not filtered by composition: a name drawn by any plugin in
  // the repo ships, which costs a symbol, never a missing glyph. Each file's
  // names are a file record: only a file whose blob changed is read.
  const tree = await buildBarrelFreeTree(pass);
  const files: string[] = [];
  for (const node of tree.byDir.values()) {
    for (const file of sourceFilesIn(tree.repo, node.dir)) {
      if (file.endsWith(".generated.ts")) continue;
      files.push(relative(root, file));
    }
  }
  // Loaded here, not at the top: the scan imports `typescript`, whose eval
  // only a pass that regenerates the manifest should pay.
  const { ICON_MANIFEST_SCAN } = await import("./icon-manifest.scan");
  for (const found of await scanFiles(tree.repo, files, ICON_MANIFEST_SCAN)) {
    for (const n of found.symbols) symbols.add(n);
    for (const n of found.brands) brands.add(n);
    for (const n of found.seti) seti.add(n);
  }
  return {
    symbols: [...symbols].sort(),
    brands: [...brands].sort(),
    seti: [...seti].sort(),
  };
}

function renderList(name: string, values: readonly string[]): string {
  if (values.length === 0) return `  ${name}: [],`;
  return [
    `  ${name}: [`,
    ...values.map((v) => `    ${JSON.stringify(v)},`),
    "  ],",
  ].join("\n");
}

function renderIconManifestContent(manifest: IconManifest): string {
  return [
    MANIFEST_HEADER,
    "",
    "export const ICON_MANIFEST: {",
    "  readonly symbols: readonly string[];",
    "  readonly brands: readonly string[];",
    "  readonly seti: readonly string[];",
    "} = {",
    renderList("symbols", manifest.symbols),
    renderList("brands", manifest.brands),
    renderList("seti", manifest.seti),
    "};",
    "",
  ].join("\n");
}

export function iconManifestPath(root: AppPath): AppPath {
  // `root`: the checkout root the caller works in.
  return joinAppPath(root, MANIFEST_REL_PATH);
}

export async function renderIconManifest(pass: CodegenPass): Promise<string> {
  return renderIconManifestContent(await collectIconManifest(pass));
}
