import {
  joinAppPath,
  type AppPath,
} from "@plugins/infra/plugins/host-fs/plugins/user-path/core";
import {
  asFsPath,
  machineNode,
} from "@plugins/framework/plugins/plugin-id/core";
import { evaluateAllBarrels } from "./evaluated-barrels";
import { writeGenerated } from "./write-generated";
import type { CodegenPass } from "./codegen-pass";

/**
 * Generates the build's table of who contributes to which server list: every
 * server contribution kind (its debug name, `defineServerContribution`) → the
 * graph nodes whose barrels contribute to it (`<pluginPath>` for a `server/`
 * half, `<pluginPath>#machine` for a `machine/` half).
 *
 * A process that started only some plugins (a job, server-core's
 * `resolveStartSet`) reads it twice: to start every contributor of a list its
 * work declares it reads, and to guard every other complete list — a read
 * whose contributors did not all start throws, naming them. The check is
 * against this table, never against a declaration, so a forgotten declaration
 * is a loud failure. Read off the evaluated barrels (no barrel imported when
 * nothing changed). Every plugin of the repo: a process ignores a node its own
 * registry does not hold.
 *
 * Not imported by any barrel — only by the partial start, dynamically — so no
 * barrel freezes a stale copy at load.
 */

const MANIFEST_REL_PATH =
  "plugins/framework/plugins/server-core/core/contributors.generated.ts";

const MANIFEST_HEADER = [
  "// DO NOT EDIT — autogenerated by `./equin build`",
  "// (see plugins/framework/plugins/tooling/plugins/codegen/core/server-contributors-gen.ts).",
  "//",
  "// Every server contribution kind (its debug name) → the graph nodes that",
  "// contribute to it (`<pluginPath>`, `<pluginPath>#machine`), and every",
  "// sink (`sink:<id>`) → the nodes handling it (`sinkHandlers`). Read by a",
  "// process that starts only some plugins (server-core's `resolveStartSet`",
  "// and the list rule). The `server-contributors-in-sync` check fails on drift.",
].join("\n");

const SERVER_HALVES = ["server", "machine"] as const;

/** A sink's handlers' key in the table (server-core's start set reads it). */
const SINK_KEY = "sink:";

type RawContribution = { _kind?: unknown };

async function collectServerContributors(
  pass: CodegenPass,
): Promise<Record<string, string[]>> {
  const ev = await evaluateAllBarrels(pass);
  const table = new Map<string, Set<string>>();
  for (const node of ev.tree.byDir.values()) {
    const path = asFsPath(node.id);
    for (const { mod, runtime } of ev.modulesOf(node)) {
      if (!(SERVER_HALVES as readonly string[]).includes(runtime)) continue;
      const graphNode = runtime === "machine" ? machineNode(path) : path;
      const def = mod.default as
        | {
            contributions?: readonly RawContribution[];
            sinkHandlers?: readonly { sinkId?: unknown }[];
          }
        | undefined;
      // A plugin handling a sink (`sinkHandlers`): recorded as `sink:<id>`,
      // so a process whose modules declare the sink starts its handler.
      for (const h of def?.sinkHandlers ?? []) {
        if (typeof h.sinkId !== "string") {
          throw new Error(
            `[server-contributors] ${graphNode}: a sinkHandlers entry has no sinkId — is it \`sinkHandler(sink, …)\`?`,
          );
        }
        const key = `${SINK_KEY}${h.sinkId}`;
        let nodes = table.get(key);
        if (nodes === undefined) table.set(key, (nodes = new Set()));
        nodes.add(graphNode);
      }
      for (const c of def?.contributions ?? []) {
        const kind = c._kind;
        if (typeof kind !== "symbol" || kind.description === undefined) {
          throw new Error(
            `[server-contributors] ${graphNode}: a contribution has no kind symbol — is it a \`defineServerContribution\` token's call?`,
          );
        }
        let nodes = table.get(kind.description);
        if (nodes === undefined)
          table.set(kind.description, (nodes = new Set()));
        nodes.add(graphNode);
      }
    }
  }
  return Object.fromEntries(
    [...table]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([kind, nodes]) => [kind, [...nodes].sort()]),
  );
}

/** Path to the committed table. */
export function serverContributorsPath(root: AppPath): AppPath {
  return joinAppPath(root, MANIFEST_REL_PATH);
}

/** The table's file contents, in memory (the in-sync check renders it too). */
export async function renderServerContributors(
  pass: CodegenPass,
): Promise<string> {
  const table = await collectServerContributors(pass);
  const lines = Object.entries(table).map(
    ([kind, nodes]) => `  ${JSON.stringify(kind)}: ${JSON.stringify(nodes)},`,
  );
  return [
    MANIFEST_HEADER,
    "",
    "export const serverContributors: Readonly<Record<string, readonly string[]>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

/** Write the table when its bytes changed. */
export async function generateServerContributors({
  pass,
}: {
  pass: CodegenPass;
}): Promise<void> {
  await writeGenerated({
    file: serverContributorsPath(pass.root),
    content: await renderServerContributors(pass),
  });
}
