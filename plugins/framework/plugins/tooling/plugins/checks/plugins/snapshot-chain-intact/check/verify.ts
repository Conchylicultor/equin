import {
  asAppPath,
  type AppPath,
} from "@plugins/infra/plugins/host-fs/plugins/user-path/core";
import { resolve } from "path";
import type {
  CheckResult,
  RepoFiles,
} from "@plugins/framework/plugins/tooling/core";
// The DAG's edges (prevId + merge-node parents) and the published set are the
// migrations plugin's: the CLI's tip join reads the same definitions, so this
// check cannot accept a history the generator would refuse, or the reverse.
import {
  analyzeSnapshotDag,
  legacySnapshotFilesIn,
  MIGRATIONS_DATA_DIR,
  NULL_SNAPSHOT_ID,
  publishedMigrationBasenames,
  readSnapshotNodes,
  schemaSnapshotStateIn,
  snapshotBodies,
  type MigrationData,
  type SnapshotDag,
  type SnapshotDagProblem,
  type SnapshotNode,
} from "@plugins/database/plugins/migrations/core";

/**
 * Every snapshot id that must have a body, and does not: each merge node
 * (recomputed from its parents), each published header node (from git), and
 * the tip (the working tree). A branch-local ordinary node below the tip is
 * skipped — its body was overwritten by the next generation and push's regen
 * consolidates it into the one migration whose body is committed as the tip.
 */
async function unresolvableBodies(
  root: AppPath,
  data: MigrationData,
  dag: SnapshotDag,
  published: ReadonlySet<string>,
): Promise<string[]> {
  const bodies = snapshotBodies(
    root,
    asAppPath(resolve(root, MIGRATIONS_DATA_DIR)),
    data,
  );
  const tip = dag.tips[0]?.id;
  const asked = [...dag.byId.values()].filter(
    (n) =>
      n.lineage === "header" &&
      (n.mergeParents !== null || n.id === tip || published.has(n.file)),
  );
  const ask = async (n: SnapshotNode): Promise<string | null> => {
    try {
      await bodies.text(n.id, n);
      return null;
    } catch (err) {
      if (!(err instanceof Error)) throw err;
      return `  ${n.file}: ${err.message}`;
    }
  };
  // Every ordinary body at once: the resolver reads all the ones git holds in
  // one batch. Then the merge nodes ONE AT A TIME: a merge node's recompute
  // reads its parents through the resolver, whose re-entry guard is per
  // resolver, so a merge node recomputed concurrently with one of its
  // descendants' recomputes would read as descending from itself.
  const missing = await Promise.all(
    asked.filter((n) => n.mergeParents === null).map(ask),
  );
  for (const n of asked.filter((n) => n.mergeParents !== null))
    missing.push(await ask(n));
  return missing.filter((m) => m !== null);
}

const list = (files: readonly string[]) =>
  files.map((f) => `  ${f}`).join("\n");

/**
 * One problem as a message + hint. `published` is only consulted for a
 * multiple-tips fork, to tell a rebase Y-fork from an unjoined upstream merge.
 */
async function explain(
  p: SnapshotDagProblem,
  published: () => Promise<ReadonlySet<string>>,
): Promise<{ message: string; hint: string }> {
  switch (p.kind) {
    case "duplicate-id":
      return {
        message: `duplicate snapshot id ${p.id}:\n${list(p.files)}`,
        hint: "Two migrations name the same snapshot. Restore them from git; a branch-local one is regenerated by `./equin build --reset-migration`.",
      };
    case "missing-parent":
      return {
        message: `${p.file} references missing parent snapshot ${p.parent}.`,
        hint: "A parent migration (or its meta/legacy-snapshots.json entry) was deleted, or a header was hand-edited. Restore from git or regenerate.",
      };
    case "merge-prev-not-parent":
      return {
        message: `merge node ${p.file}: its prevId is not one of the parents its header names.`,
        hint: "Merge nodes are generator output — never hand-edit one. Restore it from git, or reset a branch-local one with `./equin build --reset-migration`.",
      };
    case "no-root":
      return {
        message: `no root snapshot (none has prevId=${NULL_SNAPSHOT_ID}).`,
        hint: "Drizzle snapshots have been corrupted. Regenerate from a known-good state.",
      };
    case "multiple-roots":
      return {
        message: `multiple root snapshots (prevId=${NULL_SNAPSHOT_ID}):\n${list(p.files)}`,
        hint: "Only one snapshot may be the chain root. Rebase onto `main` and re-run `./equin build`.",
      };
    case "cycle":
      return {
        message: `snapshot parents form a cycle:\n${list(p.files)}`,
        hint: "The chain was hand-edited. Restore the snapshots and merge headers from git.",
      };
    case "unreachable":
      return {
        message: `${p.files.length} snapshot(s) are not reachable from the root:\n${list(p.files)}`,
        hint: "The chain has a broken link. Inspect snapshot prevIds and regenerate if needed.",
      };
    case "multiple-tips": {
      const pub = await published();
      const local = p.files.filter((f) => !pub.has(f));
      const message =
        `snapshot chain has ${p.files.length} tips (a fork no merge node joins):\n` +
        p.files
          .map(
            (f) => `  ${f}${pub.has(f) ? "  (published)" : "  (branch-local)"}`,
          )
          .join("\n");
      return local.length > 0
        ? {
            message,
            hint: "A rebase Y-fork: rebase onto `main`, then re-run `./equin build --reset-migration --migration-name <slug>` to drop this branch's migration and regenerate it against the new tip.",
          }
        : {
            message,
            hint: "Every tip is published — two `main`s were merged (an upstream update). Run `./equin build`: it writes the merge node that joins them, or stops and names the conflicting schema paths. Never delete or edit a published migration.",
          };
    }
  }
}

/**
 * The data dir as `repo` holds it — the check's `ctx.repo()`, so each listing
 * and read is a fact of its input-keyed read-set: the data dir's membership
 * (a migration added or removed) and the content of every file read (a header,
 * `legacy-snapshots.json`, the tip file).
 */
export function repoMigrationData(repo: RepoFiles): MigrationData {
  const prefix = `${MIGRATIONS_DATA_DIR}/`;
  const under = () =>
    repo.under(MIGRATIONS_DATA_DIR).map((p) => p.slice(prefix.length));
  return {
    files: async () => under().filter((rel) => !rel.includes("/")),
    metaFiles: async () =>
      under()
        .filter((rel) => rel.startsWith("meta/"))
        .map((rel) => rel.slice("meta/".length))
        .filter((rel) => !rel.includes("/")),
    start: (rel) => repo.read(`${prefix}${rel}`),
    text: (rel) => repo.read(`${prefix}${rel}`),
  };
}

/**
 * The verdict over the checkout `repo` lists. Every working-tree file it
 * reads comes through `repo`; git (the published set, the bodies of published
 * and merge nodes) is asked in `repo.root`.
 */
export async function verifySnapshotChain(
  repo: RepoFiles,
): Promise<CheckResult> {
  const root = repo.root;
  const data = repoMigrationData(repo);
  const dag = analyzeSnapshotDag(await readSnapshotNodes(data));
  const first = dag.problems[0];
  if (!first) {
    const leftover = await legacySnapshotFilesIn(data);
    if (leftover.length > 0)
      return {
        ok: false,
        message: `${leftover.length} per-migration snapshot(s) not folded into meta/legacy-snapshots.json:\n${leftover
          .slice(0, 10)
          .map((f) => `  meta/${f}`)
          .join("\n")}`,
        hint: "Run `./equin build`: it folds them (the snapshot cutover) and keeps only meta/schema.snapshot.json.",
      };
    const state = await schemaSnapshotStateIn(data, dag);
    if (!state.ok)
      return {
        ok: false,
        message: state.message,
        hint: "Run `./equin build`: it rewrites meta/schema.snapshot.json as the tip's body (from git when needed). Never hand-edit it.",
      };
    const missing = await unresolvableBodies(
      root,
      data,
      dag,
      await publishedMigrationBasenames(root),
    );
    if (missing.length > 0)
      return {
        ok: false,
        message: `${missing.length} snapshot(s) have no body anywhere (working tree, merge recompute, git):\n${missing.join("\n")}`,
        hint: "A merge node's body is recomputed from its parents; any other schema migration's body is the tip in the commit that added it. Report this — never hand-write a snapshot.",
      };
    return { ok: true };
  }
  const { message, hint } = await explain(first, () =>
    publishedMigrationBasenames(root),
  );
  const more = dag.problems.length - 1;
  return {
    ok: false,
    message: more > 0 ? `${message}\n(and ${more} more problem(s))` : message,
    hint,
  };
}
