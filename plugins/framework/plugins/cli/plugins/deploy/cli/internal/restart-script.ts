/**
 * The restart script: what `./equin deploy restart` runs on the host.
 *
 * Beside `activate-script.ts` because it holds the same health gate — a
 * restarted install is up once the release `current` names answers ready with
 * its own runId and the process that answered reports its boot settled
 * (`SETTLE_GATE_SH`), the definition a ship uses. What it does NOT have is a
 * revert: nothing changed but the process, so there is nothing to go back to;
 * a release that will not come up after a restart is reported, with its
 * journal, and the next move is a deploy.
 */
import {
  REMOTE_SCRIPT_SHEBANG,
  UNIT_TEMPLATE_PATH,
  listenAddress,
  type InstallLayout,
} from "@plugins/apps/plugins/deploy/plugins/deployments/core";
import type { HealthResponse } from "@plugins/infra/plugins/health/core";
import { sq } from "./converge-script";
import { JOURNAL_TAIL_SH, SETTLE_GATE_SH } from "./activate-script";
import {
  READY_ATTEMPTS,
  READY_INTERVAL_SEC,
  SETTLE_DEADLINE_SEC,
} from "./target";

const RUN_ID_FIELD = "runId" satisfies keyof HealthResponse;

export function restartScript(opts: {
  install: InstallLayout;
  loopbackPort: number;
}): string {
  const { install, loopbackPort } = opts;
  const base = `http://${listenAddress(loopbackPort)}`;

  return `${REMOTE_SCRIPT_SHEBANG}
# GENERATED by \`./equin deploy restart\` — do NOT edit on the host.
set -euo pipefail

# Progress to stderr: a FAILED \`sshRun\` returns stderr only (\`runScript\`).
exec 1>&2

UNIT=${sq(install.unit)}
UNIT_TEMPLATE=${sq(UNIT_TEMPLATE_PATH)}
ENV_FILE=${sq(install.envFile)}
CURRENT=${sq(install.currentLink)}
DATA=${sq(install.dataDir)}
READY_URL=${sq(`${base}/api/health/ready`)}
HEALTH_URL=${sq(`${base}/api/health`)}

${JOURNAL_TAIL_SH}

${SETTLE_GATE_SH}

# ── 1. Is there an install to restart? ───────────────────────────────────────
if [ ! -f "$UNIT_TEMPLATE" ] || [ ! -f "$ENV_FILE" ]; then
  echo "restart: this server is not set up for the site ($UNIT_TEMPLATE or $ENV_FILE is missing) — deploy it" >&2
  exit 1
fi
RELEASE="$(readlink "$CURRENT" 2>/dev/null || true)"
if [ -z "$RELEASE" ]; then
  echo "restart: nothing has been shipped to this install ($CURRENT is missing) — deploy it" >&2
  exit 1
fi
# A release dir is named by its run id (\`releaseDir\`), and /api/health names
# the run id it serves: that pair is what says the restarted process is the
# release \`current\` names.
RUN_ID="$(basename "$RELEASE")"

# ── 2. Restart. ──────────────────────────────────────────────────────────────
BEFORE="$(systemctl is-active "$UNIT" 2>/dev/null || true)"
echo "[~] $UNIT is \${BEFORE:-unknown}; restarting it on $RUN_ID"
if ! systemctl restart "$UNIT"; then
  echo "restart: systemctl restart $UNIT failed" >&2
  journal_tail
  exit 1
fi

# ── 3. The health gate: ready, serving the release \`current\` names, settled.
ok=0
body=""
for _ in $(seq 1 ${READY_ATTEMPTS}); do
  if curl -fsS -m 5 "$READY_URL" >/dev/null 2>&1; then ok=1; break; fi
  sleep ${READY_INTERVAL_SEC}
done
if [ "$ok" -ne 1 ]; then
  echo "gate: $UNIT never became ready at $READY_URL within ${
    READY_ATTEMPTS * READY_INTERVAL_SEC
  }s" >&2
  journal_tail
  exit 1
fi
body="$(curl -fsS -m 5 "$HEALTH_URL" || true)"
if ! printf '%s' "$body" | grep -Eq '"${RUN_ID_FIELD}"[[:space:]]*:[[:space:]]*"'"$RUN_ID"'"'; then
  echo "gate: ready, but /api/health does not report $RUN_ID, the release $CURRENT names:" >&2
  printf '%s\\n' "$body" >&2
  journal_tail
  exit 1
fi
STARTED_AT="$(health_started_at "$body")"
if [ -z "$STARTED_AT" ]; then
  echo "gate: /api/health names no startedAt, so no process can be followed to its settled boot" >&2
  journal_tail
  exit 1
fi
echo "[~] ready (startedAt $STARTED_AT); waiting up to ${SETTLE_DEADLINE_SEC}s for its boot to settle"
settle_status=0
settle_gate "$HEALTH_URL" "$STARTED_AT" || settle_status=$?
case "$settle_status" in
  0) echo "[ok] boot settled" ;;
  2) echo "[warn] staying up is unproven: $SETTLE_DETAIL after ${SETTLE_DEADLINE_SEC}s — passing, it is serving" ;;
  *)
    echo "gate: ready and serving $RUN_ID, then lost before its boot settled — $SETTLE_DETAIL. A crash in a post-ready boot phase repeats on every start of this release." >&2
    journal_tail
    exit 1
    ;;
esac

echo "[ok] $UNIT is serving runId $RUN_ID (restarted)"
printf '%s\\n' "$body"
`;
}
