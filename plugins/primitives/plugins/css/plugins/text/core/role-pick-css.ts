import {
  PICK_RUNGS,
  TYPE_ROLES,
  TYPE_SUBSCALE,
  typeVar,
  type PickEmphasis,
  type PickFamily,
  type PickRung,
  type TypeSubscale,
} from "./roles";

/**
 * The role picker's stylesheet: the CSS of the two classes a picked part's
 * text element wears (`role-pick`, and `role-pick-compact` in an `xs` region),
 * DERIVED from the role utilities ui-kit's `app.css` declares — the one owner
 * of every metric — so the picker cannot drift from the ladder. The type-scale
 * check holds `app.css`'s ROLE-PICK block equal to this function's output.
 *
 * Each property is ONE declaration dispatching on the generic vars the part's
 * scope sets (`--role-pick` / `--role-emphasis` / `--role-family` /
 * `--role-step`, see `rolePickScope`) with CSS `if(style(…))`. It is evaluated
 * against the element's own inherited values, so it costs about nothing — the
 * per-rung `@container style()` classes it replaces were one container query
 * per rung per element on every restyle (~25 per element, ≈35% of the style
 * time of a text-heavy window).
 *
 * The block sits in the `role-pick` cascade layer, declared after Tailwind's
 * `utilities`: it beats the element's own classes the way the query classes
 * (later-sorted variants, `!important` emphasis/family) did, and a rung that
 * has no opinion on a property (tracking on most rungs, weight on the
 * sub-scale, family on all but `code`) answers `revert-layer` — what the
 * element's classes say, the fallback rung's included. Emphasis `parent`
 * answers `inherit` (the weight of the control the words sit in).
 *
 * The `if()` block is behind `@supports (if())`: a declaration holding a
 * `var()` is never validated at parse time, so an engine without `if()` would
 * keep it and find it invalid at computed-value time — the property would
 * then INHERIT, beating the element's own classes. Such an engine (Safari,
 * Firefox in 2026) reads the same picks from the `@supports not` block of
 * container style queries instead (`fallbackBlock`) — the per-element cost
 * the `if()` block removes, paid only where nothing cheaper exists.
 */

/** The two classes a picked part's text element wears — base and compact. */
export const ROLE_PICK_CLASS = "role-pick";
export const ROLE_PICK_COMPACT_CLASS = "role-pick-compact";

/**
 * Each emphasis's weight: a shared weight token, the rung's own (`role`), or
 * the parent's (`parent`). A `Record` over the vocabulary, so a new emphasis
 * is a tsc error here until it says what it draws.
 */
const EMPHASIS_WEIGHT: Record<PickEmphasis, string | "rung"> = {
  role: "rung",
  normal: "var(--font-weight-normal)",
  medium: "var(--font-weight-medium)",
  semibold: "var(--font-weight-semibold)",
  bold: "var(--font-weight-bold)",
  parent: "inherit",
};

/** Each family's font: forced, or the rung's own (`role`: mono for `code`). */
const FAMILY_FONT: Record<PickFamily, string | "rung"> = {
  role: "rung",
  sans: "var(--font-sans)",
  mono: "var(--font-mono)",
};

/** A type property the picker sets, in output order. */
const PROPERTIES = [
  "font-family",
  "font-size",
  "line-height",
  "font-weight",
  "letter-spacing",
] as const;
type Property = (typeof PROPERTIES)[number];
type Decls = Partial<Record<Property, string>>;

/** The markers around the generated block in `app.css`. */
export const ROLE_PICK_CSS_BEGIN =
  "/* ROLE-PICK:BEGIN — generated by rolePickCss (text core); the type-scale check holds it in sync */";
export const ROLE_PICK_CSS_END = "/* ROLE-PICK:END */";

/** One `@utility` of a stylesheet: its name and body (comments stripped). */
export interface CssUtility {
  name: string;
  body: string;
}

function declsOf(body: string): Decls {
  const out: Decls = {};
  for (const m of body.matchAll(/([a-z-]+)\s*:\s*([^;]+);?/g)) {
    const prop = m[1] as Property;
    if ((PROPERTIES as readonly string[]).includes(prop))
      out[prop] = m[2]!.trim();
  }
  return out;
}

function isSubscale(rung: PickRung): boolean {
  return (TYPE_SUBSCALE as readonly string[]).includes(rung);
}

/**
 * Each rung's declarations, base and compact, read from the utilities:
 * `text-<rung>` / `text-<rung>-compact`, plus `font-<rung>` for a role whose
 * compact rung is its own (`tag`: its compact utility carries no weight, so
 * `<Text variant="tag">` pairs it with `font-tag`). The 2xs / 3xs sub-scale is
 * Tailwind's theme-generated `text-<n>`, which never compacts.
 */
function rungDecls(
  utilities: readonly CssUtility[],
): Record<PickRung, { base: Decls; compact: Decls }> {
  const byName = new Map(utilities.map((u) => [u.name, declsOf(u.body)]));
  const need = (name: string): Decls => {
    const decls = byName.get(name);
    if (decls === undefined)
      throw new Error(`rolePickCss: app.css declares no @utility ${name}`);
    return decls;
  };
  const out = {} as Record<PickRung, { base: Decls; compact: Decls }>;
  for (const rung of PICK_RUNGS) {
    if (isSubscale(rung)) {
      // What its `@theme inline` bridge inlines into `text-<n>` (a bridge
      // var is never emitted, so it cannot be read here).
      const decls: Decls = {
        "font-size": typeVar(`font-size-${rung as TypeSubscale}`),
        "line-height": typeVar(`line-height-${rung as TypeSubscale}`),
      };
      out[rung] = { base: decls, compact: decls };
      continue;
    }
    const spec = TYPE_ROLES[rung as keyof typeof TYPE_ROLES];
    const own = spec.compact === "own" ? need(`font-${rung}`) : {};
    out[rung] = {
      base: { ...need(`text-${rung}`), ...own },
      compact: { ...need(`text-${rung}-compact`), ...own },
    };
  }
  return out;
}

const pick = (rung: string) => `style(--role-pick: ${rung})`;

/** `if(<cond>: <value>; …; else: <otherwise>)`, or `otherwise` alone when no branch. */
function ifChain(
  branches: ReadonlyArray<readonly [string, string]>,
  otherwise: string | undefined,
): string | undefined {
  if (branches.length === 0) return otherwise;
  const parts = branches.map(([c, v]) => `${c}: ${v}`);
  if (otherwise !== undefined) parts.push(`else: ${otherwise}`);
  return `if(${parts.join("; ")})`;
}

/** The rung dispatch for one property: the value each rung gives it, else the cascade's. */
function rungChain(
  rungs: Record<PickRung, { base: Decls; compact: Decls }>,
  prop: Property,
  compact: boolean,
): string {
  const branches: Array<readonly [string, string]> = [];
  for (const rung of PICK_RUNGS) {
    const { base, compact: small } = rungs[rung];
    if (!compact || base[prop] === small[prop]) {
      if (base[prop] !== undefined) branches.push([pick(rung), base[prop]]);
      continue;
    }
    // The part's step: `ambient` follows the region (the compact rung),
    // `base` draws the rung it names.
    if (small[prop] !== undefined)
      branches.push([
        `${pick(rung)} and style(--role-step: ambient)`,
        small[prop],
      ]);
    if (base[prop] !== undefined)
      branches.push([`${pick(rung)} and style(--role-step: base)`, base[prop]]);
  }
  return ifChain(branches, "revert-layer")!;
}

function classBlock(
  className: string,
  rungs: Record<PickRung, { base: Decls; compact: Decls }>,
  compact: boolean,
): string {
  const decl = (prop: Property): string => {
    const byRung = rungChain(rungs, prop, compact);
    // An axis's forced values as branches; its `rung` value falls to the
    // rung dispatch.
    const axis = (table: Record<string, string>, tokenVar: string): string =>
      ifChain(
        Object.entries(table)
          .filter(([, v]) => v !== "rung")
          .map(([k, v]) => [`style(${tokenVar}: ${k})`, v] as const),
        byRung,
      )!;
    if (prop === "font-weight") return axis(EMPHASIS_WEIGHT, "--role-emphasis");
    if (prop === "font-family") return axis(FAMILY_FONT, "--role-family");
    return byRung;
  };
  const lines = PROPERTIES.map((p) => `    ${p}: ${decl(p)};`);
  return `  .${className} {\n${lines.join("\n")}\n  }`;
}

/**
 * The `@supports` condition that tells an engine with CSS `if()` from one
 * without — the one test the stylesheet's fallback block and `<Text pick>`
 * (which draws its scope wrapper only without `if()`) both use.
 */
export const CSS_IF_SUPPORTS = "(color: if(style(--role-pick: body): red))";

/** A container style query on the part's scope, `and`-joined. */
const query = (...conds: string[]) => `@container ${conds.join(" and ")}`;

/**
 * The same picks as container style queries, for an engine without `if()`
 * (Safari, Firefox in 2026): the per-element cost the `if()` block removes,
 * paid only where nothing cheaper exists. A style query reads the PARENT's
 * vars, so there the part's scope must sit on an ancestor (`<Text pick>`
 * draws a `display: contents` wrapper only in such an engine). Each rule
 * names only what the rung's utility sets; what it leaves alone falls through
 * to the element's own classes, as `revert-layer` does above. The conditions
 * are exclusive per property except emphasis / family, which come after the
 * rung rules and so win, as the `!important` classes they replace did.
 */
function fallbackBlock(
  rungs: Record<PickRung, { base: Decls; compact: Decls }>,
): string {
  const rules: string[] = [];
  const rule = (cond: string, selector: string, decls: Decls) => {
    const body = PROPERTIES.filter((p) => decls[p] !== undefined).map(
      (p) => `${p}: ${decls[p]};`,
    );
    if (body.length > 0)
      rules.push(`  ${cond} { ${selector} { ${body.join(" ")} } }`);
  };
  const withoutWeight = ({ "font-weight": _w, ...rest }: Decls): Decls => rest;
  const weightOnly = (d: Decls): Decls =>
    d["font-weight"] === undefined ? {} : { "font-weight": d["font-weight"] };
  const base = `.${ROLE_PICK_CLASS}`;
  const small = `.${ROLE_PICK_COMPACT_CLASS}`;
  const role = "style(--role-emphasis: role)";
  for (const rung of PICK_RUNGS) {
    const { base: full, compact } = rungs[rung];
    rule(query(pick(rung)), base, withoutWeight(full));
    rule(query(pick(rung), role), base, weightOnly(full));
    for (const [step, decls] of [
      ["ambient", compact],
      ["base", full],
    ] as const) {
      const stepped = `style(--role-step: ${step})`;
      rule(query(pick(rung), stepped), small, withoutWeight(decls));
      rule(query(pick(rung), stepped, role), small, weightOnly(decls));
    }
  }
  // After the rung rules, so a forced weight / family wins over the rung's.
  const both = `${base}, ${small}`;
  for (const [emphasis, weight] of Object.entries(EMPHASIS_WEIGHT))
    if (weight !== "rung")
      rule(query(`style(--role-emphasis: ${emphasis})`), both, {
        "font-weight": weight,
      });
  for (const [family, font] of Object.entries(FAMILY_FONT))
    if (font !== "rung")
      rule(query(`style(--role-family: ${family})`), both, {
        "font-family": font,
      });
  return [
    `@supports not ${CSS_IF_SUPPORTS} {`,
    "@layer role-pick {",
    ...rules,
    "}",
    "}",
  ].join("\n");
}

/** The generated block, markers included, as `app.css` carries it. */
export function rolePickCss(utilities: readonly CssUtility[]): string {
  const rungs = rungDecls(utilities);
  return [
    ROLE_PICK_CSS_BEGIN,
    `@supports ${CSS_IF_SUPPORTS} {`,
    "@layer role-pick {",
    classBlock(ROLE_PICK_CLASS, rungs, false),
    classBlock(ROLE_PICK_COMPACT_CLASS, rungs, true),
    "}",
    "}",
    fallbackBlock(rungs),
    ROLE_PICK_CSS_END,
  ].join("\n");
}
