const SIDEBAR_COOKIE_NAME = "sidebar_state";
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7;
// The desktop panel's width is a theme token (sidebar-metrics'
// `--sidebar-panel-width`, 16rem by default), republished here as the
// `--sidebar-width` every rule below reads — so the mobile sheet can still
// swap in its own width by overriding the one var.
const SIDEBAR_WIDTH = "var(--sidebar-panel-width)";
const SIDEBAR_WIDTH_MOBILE = "18rem";
const SIDEBAR_WIDTH_ICON = "3rem";
const SIDEBAR_KEYBOARD_SHORTCUT = "mod+b";

type SidebarContextProps = {
  state: "expanded" | "collapsed";
  open: boolean;
  setOpen: (open: boolean) => void;
  openMobile: boolean;
  setOpenMobile: (open: boolean) => void;
  isMobile: boolean;
  toggleSidebar: () => void;
};

const SidebarContext = React.createContext<SidebarContextProps | null>(null);

function useSidebar() {
  const context = React.useContext(SidebarContext);
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.");
  }

  return context;
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean;
  open?: boolean;
  onOpenChange?: (open: boolean) => void;
}) {
  const isMobile = useIsMobile();
  const [openMobile, setOpenMobile] = React.useState(false);

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen);
  const open = openProp ?? _open;
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value;
      if (setOpenProp) {
        setOpenProp(openState);
      } else {
        _setOpen(openState);
      }

      // This sets the cookie to keep the sidebar state.
      document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`;
    },
    [setOpenProp, open],
  );

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open);
  }, [isMobile, setOpen, setOpenMobile]);

  // Adds a keyboard shortcut to toggle the sidebar. Registered per surface, so
  // it fires only in the focused one: every open tab keeps its app shell
  // mounted, and a page-wide listener here toggled every mounted sidebar at once.
  const toggleSidebarRef = useLatestRef(toggleSidebar);
  const shortcuts = React.useMemo<Omit<ShortcutDescriptor, "surfaceId">[]>(
    () => [
      {
        id: "sidebar:toggle",
        keys: SIDEBAR_KEYBOARD_SHORTCUT,
        label: "Toggle sidebar",
        group: "View",
        handler: () => toggleSidebarRef.current(),
      },
    ],
    [toggleSidebarRef],
  );
  useSurfaceShortcuts(shortcuts);

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed";

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar],
  );

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        data-slot="sidebar-wrapper"
        style={
          {
            "--sidebar-width": SIDEBAR_WIDTH,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        className={cn(
          "group/sidebar-wrapper flex min-h-svh w-full has-data-[variant=inset]:bg-sidebar",
          className,
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  );
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  className,
  children,
  dir,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right";
  variant?: "sidebar" | "floating" | "inset";
  collapsible?: "offcanvas" | "icon" | "none";
}) {
  const { isMobile, state, openMobile, setOpenMobile } = useSidebar();

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className,
        )}
        {...props}
      >
        {children}
      </div>
    );
  }

  if (isMobile) {
    return (
      <Sheet open={openMobile} onOpenChange={setOpenMobile} {...props}>
        <SheetContent
          dir={dir}
          data-sidebar="sidebar"
          data-slot="sidebar"
          data-mobile="true"
          className="w-(--sidebar-width) bg-sidebar p-none text-sidebar-foreground [&>button]:hidden"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as React.CSSProperties
          }
          side={side}
        >
          <SheetHeader className="sr-only">
            <SheetTitle>Sidebar</SheetTitle>
            <SheetDescription>Displays the mobile sidebar.</SheetDescription>
          </SheetHeader>
          <div className="flex h-full w-full flex-col">{children}</div>
        </SheetContent>
      </Sheet>
    );
  }

  return (
    <div
      className="group peer hidden text-sidebar-foreground md:block"
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      data-slot="sidebar"
    >
      {/* This is what handles the sidebar gap on desktop */}
      <div
        data-slot="sidebar-gap"
        className={cn(
          "relative w-(--sidebar-width) bg-transparent transition-[width] duration-200 ease-linear",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon)",
        )}
      />
      {/*
        Divergence from stock shadcn: the fixed container sizes to its containing
        block (`h-full` + `inset-y-0`), NOT the viewport (`h-svh`). The app shell
        nests the sidebar inside an offset, `transform`ed container (per-tab
        keep-alive in apps-layout makes it the fixed-positioning context), so a
        viewport-height sidebar overshoots the bottom by the height of any chrome
        above it (e.g. the app tab bar) and silently clips its last item. Sizing
        to the container respects whatever offset that chrome imposes. If a shadcn
        regen reverts this, the bottom of the sidebar will clip again — keep
        `h-full`, not `h-svh`.
      */}
      <div
        data-slot="sidebar-container"
        data-side={side}
        className={cn(
          "fixed inset-y-0 z-nav hidden h-full w-(--sidebar-width) transition-[left,right,width] duration-200 ease-linear data-[side=left]:left-0 data-[side=left]:group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)] data-[side=right]:right-0 data-[side=right]:group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)] md:flex",
          // Adjust the padding for floating and inset variants.
          variant === "floating" || variant === "inset"
            ? "p-sm group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
          className,
        )}
        {...props}
      >
        <div
          data-sidebar="sidebar"
          data-slot="sidebar-inner"
          className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:shadow-sm group-data-[variant=floating]:ring-1 group-data-[variant=floating]:ring-sidebar-border"
        >
          {children}
        </div>
      </div>
    </div>
  );
}

/**
 * One state's glyph: an icon, drawn in its active form (the theme's active
 * fill) when `active` is set.
 */
export interface SidebarToggleGlyph {
  readonly icon: IconRef;
  readonly active?: boolean;
}

/**
 * The sidebar toggle's two glyphs, one per state. A pair, never one glyph: the
 * toggle's icon is how the user reads whether a click will open or close the
 * sidebar, so a design that draws one glyph must still name the other state's —
 * another icon, or the same icon in its other fill.
 */
export interface SidebarToggleIcons {
  /** Shown while the sidebar is open (the click closes it). */
  readonly open: SidebarToggleGlyph;
  /** Shown while the sidebar is closed (the click opens it). */
  readonly closed: SidebarToggleGlyph;
}

const defaultToggleIcons: SidebarToggleIcons = {
  open: { icon: leftPanelCloseIcon },
  closed: { icon: leftPanelOpenIcon },
};

function sameGlyph(a: SidebarToggleGlyph, b: SidebarToggleGlyph): boolean {
  return (
    a.icon.kind === b.icon.kind &&
    a.icon.name === b.icon.name &&
    (a.active ?? false) === (b.active ?? false)
  );
}

function SidebarTrigger({
  className,
  onClick,
  icons = defaultToggleIcons,
  ...props
}: React.ComponentProps<typeof Button> & {
  /**
   * The open/closed glyph pair, in place of the default
   * (`left-panel-close` while open, `left-panel-open` while closed).
   */
  icons?: SidebarToggleIcons;
}) {
  const { toggleSidebar, isMobile, open, openMobile } = useSidebar();
  // The icon names what a click will do, from the same state toggleSidebar flips.
  const isOpen = isMobile ? openMobile : open;
  if (sameGlyph(icons.open, icons.closed)) {
    throw new Error(
      `SidebarTrigger: the open and closed glyphs are both "${icons.open.icon.name}" in the same fill — the toggle must show which state the sidebar is in.`,
    );
  }
  const glyph = isOpen ? icons.open : icons.closed;

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      aspect="icon"
      className={cn(className)}
      onClick={(event) => {
        onClick?.(event);
        toggleSidebar();
      }}
      {...props}
    >
      <Icon icon={glyph.icon} active={glyph.active} />
      <span className="sr-only">Toggle Sidebar</span>
    </Button>
  );
}

