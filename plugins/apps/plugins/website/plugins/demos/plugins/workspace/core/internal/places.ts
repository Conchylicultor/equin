/** A stable, `demo-` Google id from a place's city and name. */
function demoGoogleId(city: string, name: string): string {
  const slug = (s: string) =>
    s
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "");
  return `demo-${slug(city)}-${slug(name)}`;
}

/**
 * When a place was saved, spread over the years and stable: a place been to
 * was saved long ago, one still to go recently — each within `[min, max)`.
 */
function savedDaysAgo(
  n: number,
  [min, max]: readonly [number, number],
): number {
  return min + ((n * 7919) % (max - min));
}

