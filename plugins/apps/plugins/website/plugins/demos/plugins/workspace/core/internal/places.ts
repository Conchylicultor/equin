function fromRows(first: number): PlaceFixture[] {
  const out: PlaceFixture[] = [];
  let n = first;
  for (const group of GROUPS) {
    for (const [
      status,
      name,
      address,
      lat,
      lng,
      kindName,
      extra = {},
    ] of group.rows) {
      const kind: Kind = KINDS[kindName];
      const tags: PlaceTagPath[] = [status === "w" ? WANT : BEEN];
      if (status === "f") tags.push(FAVORITE);
      if (group.trip !== undefined) tags.push(group.trip);
      tags.push(kind.tag);
      if (extra.p !== undefined) tags.push(PRICE[extra.p]);
      tags.push(...(extra.tags ?? []));
      out.push({
        id: placeId(n),
        place: {
          kind: "google",
          googlePlaceId: demoGoogleId(group.city, name),
          name,
          address,
          lat,
          lng,
          primaryType: kind.primaryType,
          types: [kind.primaryType, ...kind.types],
        },
        tags,
        icon: extra.icon ?? kind.icon,
        ...(extra.note === undefined ? {} : { note: extra.note }),
        savedDaysAgo: savedDaysAgo(n, status === "w" ? group.want : group.been),
      });
      n++;
    }
  }
  for (const custom of PARIS_CUSTOM) out.push({ ...custom, id: placeId(n++) });
  return out;
}

